// Timeline markers → the exported clock (specdocs/101326_skia-target.md
// §3.5a, M3 lane B). Both bundle kinds (emit.ts, scene-emit.ts) ship
// `toolbox-clock.ts`: the composition's named segments as SEGMENTS
// (name → [startSec, endSec)), MARKERS (name → sec), and useToolboxClock(),
// the master clock plus its controls. The module is self-contained — it
// imports nothing from the bundle — so any emitter (a future export mode
// included) can add it with one line.
//
// Clock contract (bundle format 3):
//   const clock = useToolboxClock({ playing?, loop?, start?, segment?, onSegmentEnd? });
//   <ToolboxScene time={clock.time} … />          // the SharedValue, unchanged
//   clock.play() / pause() / seek(sec) / playAll({ loop })
//   clock.playSegment("intro", { loop?, thenLoop? }) / loopSegment("idle")
// Every control is a worklet: call it from React (onPress) or from a gesture
// / animated reaction on the UI thread. The clock advances in one
// useFrameCallback; its window state lives in shared values, so a control
// called from either thread takes effect on the next UI frame.
//
// Exactness. A frame-aligned device clock must land on the same ticks as
// the editor (ticksAt snaps within 1e-6 tick). The clock therefore treats a
// time within that tolerance of the window end as the end, and a loop wraps
// by carrying only the overshoot past the end back to the start
// (start + overshoot mod length). Accumulated float drift is discarded at
// every wrap instead of compounding, so loop N shows the same frames as
// loop 1 — the gate replays thousands of fake frames to prove it.

import { deriveSegments, type TimelineMarker } from "@/lib/timeline-markers";
import { durationSecOf, type EmitTimeline } from "./emit-shared";

export interface ExportSegment {
  name: string;
  // Seconds on the exported clock; end exclusive.
  start: number;
  end: number;
  startFrame: number;
  endFrame: number;
  kind: "range" | "next";
}

export interface ExportMarker {
  name: string;
  frame: number;
  time: number;
}

export interface ExportSegments {
  segments: ExportSegment[];
  markers: ExportMarker[];
  // Duplicate names, out-of-range markers, clamped spans — export warnings.
  warnings: string[];
}

export const NO_EXPORT_SEGMENTS: ExportSegments = { segments: [], markers: [], warnings: [] };

// The request's markers on the exported clock (`timeline` = the request's
// timeline; markers are composition frames, already shifted onto the
// target's own clock by the caller when it differs).
export function exportSegments(
  markers: readonly TimelineMarker[] | undefined,
  timeline: { fps: number; ticksPerFrame: number; sceneDurationTicks: number }
): ExportSegments {
  if (!markers || markers.length === 0) return NO_EXPORT_SEGMENTS;
  const fps = timeline.fps;
  const frames = timeline.sceneDurationTicks / timeline.ticksPerFrame;
  const d = deriveSegments(markers, frames);
  return {
    segments: d.segments.map((s) => ({
      name: s.name,
      start: s.startFrame / fps,
      end: s.endFrame / fps,
      startFrame: s.startFrame,
      endFrame: s.endFrame,
      kind: s.kind,
    })),
    markers: d.markers.map((m) => ({ name: m.name, frame: m.frame, time: m.frame / fps })),
    warnings: d.issues.map((i) => `Timeline markers: ${i.message}`),
  };
}

// manifest.json's view.
export function manifestSegments(s: ExportSegments) {
  return {
    segments: s.segments.map((x) => ({
      name: x.name,
      start: x.start,
      end: x.end,
      frames: [x.startFrame, x.endFrame],
      kind: x.kind,
    })),
    markers: s.markers.map((m) => ({ name: m.name, frame: m.frame, time: m.time })),
  };
}

const lit = (v: number) => JSON.stringify(v);

// toolbox-clock.ts — see the header for the contract. `header` is the
// bundle's "Generated by toolbox" banner.
export function clockModuleSource(t: EmitTimeline, s: ExportSegments, header: string): string {
  const durationSec = durationSecOf(t);
  // ticksAt's snap tolerance (1e-6 tick), in seconds: times this close to a
  // window edge ARE the edge.
  const eps = 1e-6 / (t.fps * t.ticksPerFrame);
  const segs = s.segments.length
    ? `{\n${s.segments
        .map(
          (x) =>
            `  ${JSON.stringify(x.name)}: [${lit(x.start)}, ${lit(x.end)}], // frames ${x.startFrame}–${x.endFrame}${x.kind === "range" ? " (range)" : ""}`
        )
        .join("\n")}\n} as const`
    : `{} as const`;
  const marks = s.markers.length
    ? `{\n${s.markers.map((m) => `  ${JSON.stringify(m.name)}: ${lit(m.time)}, // frame ${m.frame}`).join("\n")}\n} as const`
    : `{} as const`;
  return `${header}
import { useCallback, useMemo } from "react";
import { useFrameCallback, useSharedValue, type FrameInfo, type SharedValue } from "react-native-reanimated";
import { isWorkletFunction, scheduleOnRN } from "react-native-worklets";

// The toolbox scene length the clock plays over, in seconds.
export const DURATION_SEC = ${lit(durationSec)};

// Named segments from the composition's timeline markers: name → [startSec, endSec).
// A marker runs to the next marker (or the scene end); a marker with a duration
// is its own range.
export const SEGMENTS = ${segs};
export type SegmentName = keyof typeof SEGMENTS;

// Each marker's time in seconds — a seek() target, or a withTiming(…) target for
// clock.time after pause().
export const MARKERS = ${marks};
export type MarkerName = keyof typeof MARKERS;

// Times within this of a window edge are the edge (ticksAt's tolerance).
const EPS = ${lit(eps)};

export interface PlaySegmentOptions {
  // Loop the segment. Default false: play once, then hold on its end instant
  // (the pose the next segment starts from) and pause.
  loop?: boolean;
  // When this segment ends, continue straight into that one, looping —
  // "intro once, then idle" with no dropped or repeated frame.
  thenLoop?: SegmentName;
}

export interface ToolboxClockOptions {
  // Start playing at mount. Default true.
  playing?: boolean;
  // Loop the window. Default true. playSegment / loopSegment set their own.
  loop?: boolean;
  // Start time in seconds. Default: the window's start.
  start?: number;
  // Play this segment instead of the whole timeline.
  segment?: SegmentName;
  // The window reached its end: once for a play-once segment, on every wrap of
  // a loop. \`segment\` is null for the whole timeline. A worklet runs on the UI
  // thread in the same frame (it may call the controls); a plain function is
  // scheduled on the JS thread.
  onSegmentEnd?: (segment: SegmentName | null) => void;
}

export interface ToolboxClock {
  // Seconds on the toolbox timeline: pass it as \`time\`. To drive it yourself
  // (a gesture, withTiming to a marker), pause() first.
  time: SharedValue<number>;
  playing: SharedValue<boolean>;
  // The segment playing, or null for the whole timeline.
  segment: SharedValue<SegmentName | null>;
  // Resume. At the end of a play-once window, restart it.
  play(): void;
  pause(): void;
  // Jump to \`seconds\` (clamped to the timeline). Inside the playing segment it
  // keeps playing that segment; outside, the clock returns to the whole timeline.
  seek(seconds: number): void;
  // Play a segment from its start. False (and no change) for an unknown name.
  playSegment(name: SegmentName, opts?: PlaySegmentOptions): boolean;
  loopSegment(name: SegmentName): boolean;
  // Back to the whole timeline, from 0.
  playAll(opts?: { loop?: boolean }): void;
}

function rangeOf(name: string | null | undefined): readonly [number, number] | null {
  "worklet";
  if (name == null || !Object.prototype.hasOwnProperty.call(SEGMENTS, name)) return null;
  return (SEGMENTS as Record<string, readonly [number, number]>)[name];
}

// One master clock in seconds, advanced on the UI thread.
export function useToolboxClock(opts: ToolboxClockOptions = {}): ToolboxClock {
  const { playing: autoplay = true, loop = true, start, segment: initial, onSegmentEnd } = opts;
  const first = rangeOf(initial);
  const time = useSharedValue(start ?? (first ? first[0] : 0));
  const playing = useSharedValue(autoplay);
  const segment = useSharedValue<SegmentName | null>(first ? (initial as SegmentName) : null);
  // The playing window [from, to), whether it loops, and what follows it.
  const from = useSharedValue(first ? first[0] : 0);
  const to = useSharedValue(first ? first[1] : DURATION_SEC);
  const looping = useSharedValue(loop);
  const then = useSharedValue<SegmentName | null>(null);
  const endIsWorklet = onSegmentEnd !== undefined && isWorkletFunction(onSegmentEnd);

  // Memoized so the frame callback registers once: a re-registered callback
  // gets timeSincePreviousFrame = null on its first frame (a dropped frame of
  // time per re-render).
  const advance = useCallback(
    (frame: FrameInfo) => {
      "worklet";
      if (!playing.value) return;
      const dt = (frame.timeSincePreviousFrame ?? 0) / 1000;
      const end = to.value;
      const next = time.value + dt;
      if (next < end - EPS) {
        time.value = next;
        return;
      }
      const ended = segment.value;
      // Past the end by \`over\` (0 when within EPS of it).
      const over = next > end ? next - end : 0;
      const after = rangeOf(then.value);
      if (after !== null) {
        const len = after[1] - after[0];
        segment.value = then.value;
        then.value = null;
        from.value = after[0];
        to.value = after[1];
        looping.value = true;
        const t = after[0] + (len > 0 ? over % len : 0);
        time.value = t < after[1] - EPS ? t : after[0];
      } else if (looping.value) {
        const a = from.value;
        const len = end - a;
        const t = a + (len > 0 ? over % len : 0);
        time.value = t < end - EPS ? t : a;
      } else {
        time.value = end;
        playing.value = false;
      }
      if (onSegmentEnd !== undefined) {
        if (endIsWorklet) onSegmentEnd(ended);
        else scheduleOnRN(onSegmentEnd, ended);
      }
    },
    [onSegmentEnd, endIsWorklet]
  );
  useFrameCallback(advance, true);

  // Shared values are stable and \`loop\` is read at mount like the other
  // options, so the controls are built once.
  return useMemo<ToolboxClock>(() => {
    const setWindow = (name: SegmentName | null, a: number, b: number, loops: boolean) => {
      "worklet";
      segment.value = name;
      then.value = null;
      from.value = a;
      to.value = b;
      looping.value = loops;
    };
    const play = () => {
      "worklet";
      if (!looping.value && time.value >= to.value - EPS) time.value = from.value;
      playing.value = true;
    };
    const pause = () => {
      "worklet";
      playing.value = false;
    };
    const seek = (seconds: number) => {
      "worklet";
      const t = Math.min(Math.max(Number.isFinite(seconds) ? seconds : 0, 0), DURATION_SEC);
      if (segment.value !== null && (t < from.value - EPS || t > to.value + EPS)) setWindow(null, 0, DURATION_SEC, loop);
      time.value = t;
    };
    const playSegment = (name: SegmentName, o?: PlaySegmentOptions) => {
      "worklet";
      const r = rangeOf(name);
      if (r === null) return false;
      setWindow(name, r[0], r[1], o?.loop ?? false);
      if (o?.thenLoop !== undefined && rangeOf(o.thenLoop) !== null) then.value = o.thenLoop;
      time.value = r[0];
      playing.value = true;
      return true;
    };
    const loopSegment = (name: SegmentName) => {
      "worklet";
      return playSegment(name, { loop: true });
    };
    const playAll = (o?: { loop?: boolean }) => {
      "worklet";
      setWindow(null, 0, DURATION_SEC, o?.loop ?? loop);
      time.value = 0;
      playing.value = true;
    };
    return { time, playing, segment, play, pause, seek, playSegment, loopSegment, playAll };
  }, []);
}
`;
}
