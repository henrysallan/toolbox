// ---- literals ------------------------------------------------------------------

function lit(v: unknown): string {
  if (typeof v === "number") {
    if (Number.isNaN(v)) return "NaN";
    if (!Number.isFinite(v)) return v > 0 ? "Infinity" : "-Infinity";
    return Object.is(v, -0) ? "-0" : String(v);
  }
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(lit).join(", ")}]`;
  if (v === null || v === undefined) return "undefined";
  return JSON.stringify(v);
}

const objKey = (k: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

// ---- SVG path verb signature (usePathInterpolation needs equal verbs) ---------------

// Skia's SVG parser maps H/V → line, S → cubic, T → quad, the extra pairs
// after M → lines, and arcs → a sweep-dependent number of conics. Equal
// signatures ⇒ isInterpolatable; arcs never qualify.
export function svgPathSignature(d: string): string | null {
  const tokens = d.match(/[MmLlHhVvCcSsQqTtAaZz]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g);
  if (!tokens) return "";
  const arity: Record<string, number> = { M: 2, L: 2, T: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, A: 7, Z: 0 };
  const verb: Record<string, string> = { M: "M", L: "L", H: "L", V: "L", C: "C", S: "C", Q: "Q", T: "Q", Z: "Z" };
  let sig = "";
  let i = 0;
  while (i < tokens.length) {
    const cmd = tokens[i++].toUpperCase();
    if (!(cmd in arity)) return null;
    if (cmd === "A") return null;
    let n = 0;
    while (i < tokens.length && !/[A-Za-z]/.test(tokens[i])) {
      n++;
      i++;
    }
    const a = arity[cmd];
    if (a === 0) {
      if (n) return null;
      sig += "Z";
      continue;
    }
    if (n === 0 || n % a) return null;
    for (let k = 0; k < n / a; k++) sig += cmd === "M" && k > 0 ? "L" : verb[cmd];
  }
  return sig;
}

// ---- series compression ----------------------------------------------------------------

const same = (a: unknown, b: unknown) =>
  Array.isArray(a) && Array.isArray(b) ? a.length === b.length && a.every((x, i) => Object.is(x, b[i])) : Object.is(a, b);

// lerp: keep both ends of every run of equal values (interpolating between
// equal neighbours reproduces the run exactly); step: keep run starts.
// (emit-baked.ts bakes a sampled series over the same frames.)
export function compress(values: BindValue[], mode: "lerp" | "step"): { f: number[]; v: BindValue[] } {
  const f: number[] = [];
  const v: BindValue[] = [];
  const last = values.length - 1;
  values.forEach((x, i) => {
    const keep =
      mode === "step"
        ? i === 0 || !same(x, values[i - 1])
        : i === 0 || i === last || !same(x, values[i - 1]) || !same(x, values[i + 1]);
    if (keep) {
      f.push(i);
      v.push(x);
    }
  });
  return { f, v };
}

function seriesMode(pb: PlannedBind & { plan: { kind: "sampled" } }): "lerp" | "lerpN" | "step" {
  const vals = pb.plan.values;
  if (pb.role === "number") return "lerp";
  if (pb.role === "array") {
    const n = (vals[0] as number[]).length;
    return vals.every((x) => Array.isArray(x) && x.length === n) ? "lerpN" : "step";
  }
  return "step";
}

// ---- JSX tree -----------------------------------------------------------------------------

interface El {
  tag: string;
  props: [string, string | El][];
  children: El[];
  // A JSX expression child (`{E0}`) instead of an element: a drawing
  // emitted once and reused (Copy to Points (Skia)'s instance under N
  // copy groups).
  expr?: string;
}

const el = (tag: string, props: [string, string | El | undefined][] = [], children: El[] = []): El => ({
  tag,
  props: props.filter((p): p is [string, string | El] => p[1] !== undefined),
  children,
});

const exprEl = (code: string): El => ({ tag: "", props: [], children: [], expr: code });

function renderEl(e: El, indent: string): string {
  if (e.expr !== undefined) return `${indent}{${e.expr}}`;
  const inner = indent + "  ";
  const propText = (k: string, v: string | El, pIndent: string) => {
    if (typeof v !== "string") return `${k}={${renderEl(v, pIndent).trimStart()}}`;
    if (v === "true") return k;
    if (/^"[A-Za-z0-9_]*"$/.test(v)) return `${k}=${v}`;
    return `${k}={${v}}`;
  };
  const one = e.props.map(([k, v]) => " " + propText(k, v, indent)).join("");
  const multiline = (indent.length + e.tag.length + one.length > 100 || one.includes("\n")) && e.props.length > 1;
  const open = multiline
    ? `${indent}<${e.tag}\n${e.props.map(([k, v]) => `${inner}${propText(k, v, inner)}`).join("\n")}\n${indent}`
    : `${indent}<${e.tag}${one}`;
  if (!e.children.length) return `${open}${multiline ? "/>" : " />"}`;
  return `${open}>\n${e.children.map((c) => renderEl(c, inner)).join("\n")}\n${indent}</${e.tag}>`;
}

// ---- values ----------------------------------------------------------------------------------

// static: a literal / module constant. render: computed during render from
// a hook (a loaded image or font). anim: a shared value (`direct` as a prop,
// `inner` inside a worklet).
type V = { kind: "static"; code: string } | { kind: "render"; code: string } | { kind: "anim"; inner: string; direct: string };

const prop = (v: V) => (v.kind === "anim" ? v.direct : v.code);

// Animated binds that evaluate to the same thing (one keyframed param read
// by three props) share one sampleBinds key: bind id → the key it reads.
export function sampleKeys(plan: ScenePlan): Map<string, string> {
  const byKey = new Map<string, string>();
  const out = new Map<string, string>();
  for (const b of plan.binds) {
    const p = b.plan;
    let key: string;
    if (p.kind === "track") key = JSON.stringify(["t", b.role, p.pick ?? null, p.tracks]);
    else if (p.kind === "clock") key = "clock";
    else if (p.kind === "sampled") key = JSON.stringify(["s", b.role, p.values]);
    else if (p.kind === "expr") key = JSON.stringify(["e", b.role, p.scale ?? null, programKey(p.program)]);
    else continue;
    const first = byKey.get(key);
    if (first) out.set(b.id, first);
    else {
      byKey.set(key, b.id);
      out.set(b.id, b.id);
    }
  }
  return out;
}

class SceneEmitter {
  rn = new Set<string>(["Group"]);
  rnTypes = new Set<string>();
  rea = new Set<string>();
  helpers = new Set<string>();
  consts: string[] = [];
  hooks: string[] = [];
  timelineImports = new Set<string>(["CANVAS"]);
  timelineDecls: string[] = [];
  effects: { sksl: string; where: string[]; fused: string[] }[] = [];
  private n = 0;
  private pathHooks = new Map<string, V>();
  // Enclosing groups' opacities, outermost first (see the Paragraph case).
  private groupOpacity: Bind<number>[] = [];
  private assetHooks = new Map<string, string>();
  needB = false;
  needF = false;
  // `import { PixelRatio } from "react-native"` (atlas sprite sheets).
  needPixelRatio = false;
  readonly keys: Map<string, string>;
  // Drawing nodes the tree holds more than once (one instance under N copy
  // groups): emitted once as `const E<k> = (…)` and referenced as {E<k>}.
  private shared = new Map<SkiaNode, number>();
  private sharedEl = new Map<SkiaNode, El>();
  // Render-phase hook values (loaded images / fonts) the walk references —
  // collected while emitting a sprite sheet's sub-scene, whose texture must
  // re-render when they land.
  private renderRefs: Set<string> | null = null;
  private atlasScaleName: string | null = null;
  // Sprite-sheet textures by drawing and rect (two atlases of one drawing
  // share one useTexture).
  private sheets = new Map<SkiaNode, Map<string, string>>();

  constructor(private plan: ScenePlan) {
    this.keys = sampleKeys(plan);
    const seen = new Map<SkiaNode, number>();
    const visit = (n: SkiaNode | undefined) => {
      if (!n || typeof n !== "object") return;
      const c = (seen.get(n) ?? 0) + 1;
      seen.set(n, c);
      if (c > 1) return;
      if (n.k === "group") n.children.forEach(visit);
      if (n.k === "atlas" && n.texture) visit(n.texture.node);
    };
    visit(plan.scene.root);
    for (const [n, c] of seen) if (c > 1) this.shared.set(n, c);
  }

  private noteRender(name: string): string {
    this.renderRefs?.add(name);
    return name;
  }

  // Device px per scene px for sprite sheets (crisp at 3×): the canvas's
  // pixel ratio × the root group's scale, rounded so a 1:1 web canvas is
  // exactly 1.
  private atlasScale(): string {
    if (!this.atlasScaleName) {
      this.atlasScaleName = "AK";
      this.needPixelRatio = true;
      this.hooks.push(
        `// Device px per toolbox px — atlas sprite sheets rasterise at this density.\n  const AK = Math.round(PixelRatio.get() * Math.max(width / CANVAS.width, height / CANVAS.height) * 1e6) / 1e6;`
      );
    }
    return this.atlasScaleName;
  }

  // The sampleBinds key an animated bind reads (null: not animated).
  keyOf(b: Bind<unknown>): string | null {
    const pb = this.plan.bindFor.get(b);
    return pb ? (this.keys.get(pb.id) ?? null) : null;
  }

  private name(prefix: string) {
    return `${prefix}${this.n++}`;
  }

  bind(b: Bind<unknown> | undefined): V {
    if (!b) return { kind: "static", code: "undefined" };
    const pb = this.plan.bindFor.get(b);
    if (!pb || pb.plan.kind === "static") return { kind: "static", code: lit(pb?.plan.kind === "static" ? pb.plan.value : b.v) };
    if (pb.plan.kind === "refused") throw new Error(`emitSceneBundle: ${pb.path} is refused (${pb.plan.reason}) — plan first.`);
    const key = this.keys.get(pb.id) ?? pb.id;
    if (pb.plan.kind === "sampled" && pb.role === "path") {
      const canonical = this.plan.binds.find((x) => x.id === key) ?? pb;
      return this.pathSeries(canonical as PlannedBind & { plan: { kind: "sampled" } });
    }
    this.needB = true;
    this.rn.add("select");
    return { kind: "anim", inner: `B.value.${key}`, direct: `select(B, "${key}")` };
  }

  private pathSeries(pb: PlannedBind & { plan: { kind: "sampled" } }): V {
    const hit = this.pathHooks.get(pb.id);
    if (hit) return hit;
    const vals = pb.plan.values as string[];
    const sig0 = svgPathSignature(vals[0]);
    const interp = sig0 !== null && vals.every((d) => svgPathSignature(d) === sig0);
    const s = compress(vals, interp ? "lerp" : "step");
    const data = `PATH_${pb.id}`;
    this.timelineDecls.push(
      `// ${pb.path}: ${pb.plan.from} — ${s.f.length} distinct-frame paths, ${interp ? "interpolated (equal verbs)" : "stepped (verbs change)"}.\nexport const ${data}: Series<string> = ${JSON.stringify(s)};`
    );
    this.timelineImports.add(data);
    this.helpers.add("parsePath");
    this.needF = true;
    const hook = `P_${pb.id}`;
    if (interp) {
      this.consts.push(`const PATHS_${pb.id} = ${data}.v.map(parsePath);`);
      this.rn.add("usePathInterpolation");
      this.hooks.push(`const ${hook} = usePathInterpolation(F, ${data}.f, PATHS_${pb.id}, "clamp");`);
    } else {
      this.consts.push(`const PATHS_${pb.id} = { f: ${data}.f, v: ${data}.v.map(parsePath) };`);
      this.timelineImports.add("seriesStep");
      this.rea.add("useDerivedValue");
      this.hooks.push(`const ${hook} = useDerivedValue(() => seriesStep(PATHS_${pb.id}, F.value));`);
    }
    const v: V = { kind: "anim", inner: `${hook}.value`, direct: hook };
    this.pathHooks.set(pb.id, v);
    return v;
  }

  // Several values → one prop value.
  composite(vs: V[], build: (codes: string[]) => string, o: { hoist?: boolean; type?: string } = {}): V {
    if (vs.some((v) => v.kind === "anim")) {
      const name = this.name("D");
      this.rea.add("useDerivedValue");
      if (o.type) this.rnTypes.add(o.type);
      const codes = vs.map((v) => (v.kind === "anim" ? v.inner : v.code));
      const body = build(codes);
      this.hooks.push(`const ${name} = useDerivedValue(${o.type ? `(): ${o.type} => ` : "() => "}${body.startsWith("{") ? `(${body})` : body});`);
      return { kind: "anim", inner: `${name}.value`, direct: name };
    }
    const code = build(vs.map((v) => (v.kind === "anim" ? "" : v.code)));
    if (vs.some((v) => v.kind === "render")) return { kind: "render", code };
    if (o.hoist) {
      const name = this.name("K");
      this.consts.push(`const ${name} = ${code};`);
      return { kind: "static", code: name };
    }
    return { kind: "static", code };
  }

  vec(xy: BindXY): V {
    this.rn.add("vec");
    return this.composite([this.bind(xy[0]), this.bind(xy[1])], ([x, y]) => `vec(${x}, ${y})`);
  }

  list(bs: Bind<unknown>[]): V {
    return this.composite(bs.map((b) => this.bind(b)), (c) => `[${c.join(", ")}]`);
  }

  private rect(x: Bind<number>, y: Bind<number>, w: Bind<number>, h: Bind<number>, wrap: (r: string, extra: string[]) => string, extra: Bind<number>[] = []): V {
    this.rn.add("rect");
    return this.composite([x, y, w, h, ...extra].map((b) => this.bind(b)), (c) => wrap(`rect(${c[0]}, ${c[1]}, ${c[2]}, ${c[3]})`, c.slice(4)), { hoist: true });
  }

  points(pts: Bind<number[]>): V {
    this.helpers.add("toPoints");
    this.rn.add("vec");
    return this.composite([this.bind(pts)], ([p]) => `toPoints(${p})`, { hoist: true });
  }

  path(d: Bind<string>): V {
    const v = this.bind(d);
    if (v.kind !== "static") return v;
    this.helpers.add("parsePath");
    return this.composite([v], ([s]) => `parsePath(${s})`, { hoist: true });
  }

  // A geometry as an SkPath (trimmed shapes, non-rect clips).
  geomPath(g: GeomIR): V {
    this.rn.add("Skia");
    switch (g.k) {
      case "rect":
        if (g.r) {
          this.rn.add("rrect");
          return this.rect(g.x, g.y, g.w, g.h, (r, [rr]) => `Skia.Path.RRect(rrect(${r}, ${rr}, ${rr}))`, [g.r]);
        }
        return this.rect(g.x, g.y, g.w, g.h, (r) => `Skia.Path.Rect(${r})`);
      case "circle":
        return this.composite([g.cx, g.cy, g.r].map((b) => this.bind(b)), (c) => `Skia.Path.Circle(${c[0]}, ${c[1]}, ${c[2]})`, { hoist: true });
      case "oval":
        return this.rect(g.x, g.y, g.w, g.h, (r) => `Skia.Path.Oval(${r})`);
      case "line":
        this.rn.add("vec");
        return this.composite(
          [...g.p1, ...g.p2].map((b) => this.bind(b)),
          (c) => `Skia.Path.Line(vec(${c[0]}, ${c[1]}), vec(${c[2]}, ${c[3]}))`,
          { hoist: true }
        );
      case "path":
        return this.path(g.d);
      case "points":
        this.helpers.add("toPoints");
        this.rn.add("vec");
        // Open unless it is a polygon (Skia PathBuilder.addPolygon, as the
        // preview converts it).
        return this.composite([this.bind(g.pts)], ([p]) => `Skia.Path.Polygon(toPoints(${p}), ${g.mode === "polygon"})`, { hoist: true });
    }
  }

  clip(g: GeomIR): V {
    if (g.k === "rect") {
      if (g.r) {
        this.rn.add("rrect");
        return this.rect(g.x, g.y, g.w, g.h, (r, [rr]) => `rrect(${r}, ${rr}, ${rr})`, [g.r]);
      }
      return this.rect(g.x, g.y, g.w, g.h, (r) => r);
    }
    return this.geomPath(g);
  }

  image(asset: string): string {
    const hit = this.assetHooks.get(`img:${asset}`);
    if (hit) return this.noteRender(hit);
    const name = this.name("IMG");
    this.rn.add("useImage");
    this.hooks.push(`const ${name} = useImage(ASSET_SOURCES[${lit(asset)}]);`);
    this.assetHooks.set(`img:${asset}`, name);
    return this.noteRender(name);
  }

  font(asset: string, size: Bind<number>): V {
    const sv = this.bind(size);
    if (sv.kind !== "anim") {
      const key = `font:${asset}:${sv.code}`;
      let name = this.assetHooks.get(key);
      if (!name) {
        name = this.name("FONT");
        this.rn.add("useFont");
        this.hooks.push(`const ${name} = useFont(ASSET_SOURCES[${lit(asset)}], ${sv.code});`);
        this.assetHooks.set(key, name);
      }
      return { kind: "render", code: this.noteRender(name) };
    }
    let tf = this.assetHooks.get(`tf:${asset}`);
    if (!tf) {
      tf = this.name("TF");
      this.rn.add("useTypeface");
      this.hooks.push(`const ${tf} = useTypeface(ASSET_SOURCES[${lit(asset)}]);`);
      this.assetHooks.set(`tf:${asset}`, tf);
    }
    this.noteRender(tf);
    this.rn.add("Skia");
    return this.composite([{ kind: "render", code: tf }, sv], ([t, s]) => `${t} ? Skia.Font(${t}, ${s}) : null`);
  }

  // A font provider for Paragraphs; the family is the asset id.
  fonts(asset: string): V {
    let name = this.assetHooks.get(`fonts:${asset}`);
    if (!name) {
      name = this.name("FONTS");
      this.rn.add("useFonts");
      // An unbundled font (ASSET_SOURCES[id] is null) registers no typeface.
      const a = this.plan.assets.find((x) => x.id === asset);
      const bundled = !!a && !!assetBytesOf(a.url, this.plan.assetBytes);
      this.hooks.push(`const ${name} = useFonts({ ${JSON.stringify(asset)}: ${bundled ? `[ASSET_SOURCES[${lit(asset)}]]` : "[]"} });`);
      this.assetHooks.set(`fonts:${asset}`, name);
    }
    return { kind: "render", code: this.noteRender(name) };
  }

  effect(p: SkslProgramIR, where: string): string {
    let i = this.effects.findIndex((e) => e.sksl === p.sksl);
    if (i < 0) {
      i = this.effects.length;
      this.effects.push({ sksl: p.sksl, where: [], fused: [] });
      this.helpers.add("makeEffect");
      this.consts.push(`const EFFECT_${i} = makeEffect(SKSL_${i}, ${i});`);
    }
    const e = this.effects[i];
    e.where.push(where);
    for (const f of p.fused ?? []) if (!e.fused.includes(f)) e.fused.push(f);
    return `EFFECT_${i}`;
  }

  uniforms(p: SkslProgramIR): V {
    const keys = Object.keys(p.uniforms);
    return this.composite(
      keys.map((k) => this.bind(p.uniforms[k])),
      (c) => `{ ${keys.map((k, i) => `${objKey(k)}: ${c[i]}`).join(", ")} }`,
      { hoist: true, type: "Uniforms" }
    );
  }

  // ---- IR → elements --------------------------------------------------------------------

  stops(stops: GradientStopIR[]): [string, string][] {
    return [
      ["colors", prop(this.list(stops.map((s) => s.color)))],
      ["positions", prop(this.list(stops.map((s) => s.pos)))],
    ];
  }

  shader(s: ShaderIR, where: string): El {
    switch (s.k) {
      case "runtime": {
        this.rn.add("Shader");
        const src = this.effect(s.program, where);
        return el(
          "Shader",
          [
            ["source", src],
            ["uniforms", prop(this.uniforms(s.program))],
          ],
          s.program.children.map((c) => this.shader(c.shader, `${where} › ${c.name}`))
        );
      }
      case "linear":
        this.rn.add("LinearGradient");
        return el("LinearGradient", [["start", prop(this.vec(s.start))], ["end", prop(this.vec(s.end))], ...this.stops(s.stops), ["mode", s.tile && lit(s.tile)]]);
      case "radial":
        this.rn.add("RadialGradient");
        return el("RadialGradient", [["c", prop(this.vec(s.c))], ["r", prop(this.bind(s.r))], ...this.stops(s.stops), ["mode", s.tile && lit(s.tile)]]);
      case "sweep": {
        // IR angles are radians; Skia's sweep takes degrees.
        this.rn.add("SweepGradient");
        const deg = (b: Bind<number> | undefined) => {
          if (!b) return undefined;
          const v = this.bind(b);
          if (v.kind === "static" && typeof (this.plan.bindFor.get(b)?.plan as { value?: unknown })?.value === "number") {
            return lit(((this.plan.bindFor.get(b)!.plan as { value: number }).value * 180) / Math.PI);
          }
          return prop(this.composite([v], ([a]) => `(${a} * 180) / Math.PI`));
        };
        return el("SweepGradient", [["c", prop(this.vec(s.c))], ["start", deg(s.start)], ["end", deg(s.end)], ...this.stops(s.stops)]);
      }
      case "conical":
        this.rn.add("TwoPointConicalGradient");
        return el("TwoPointConicalGradient", [
          ["start", prop(this.vec(s.c0))],
          ["startR", prop(this.bind(s.r0))],
          ["end", prop(this.vec(s.c1))],
          ["endR", prop(this.bind(s.r1))],
          ...this.stops(s.stops),
          ["mode", s.tile && lit(s.tile)],
        ]);
      case "image":
        this.rn.add("ImageShader");
        return el("ImageShader", [
          ["image", this.image(s.asset)],
          ["fit", lit(s.fit)],
          ["x", prop(this.bind(s.rect[0]))],
          ["y", prop(this.bind(s.rect[1]))],
          ["width", prop(this.bind(s.rect[2]))],
          ["height", prop(this.bind(s.rect[3]))],
          ["tx", s.tile && lit(s.tile)],
          ["ty", s.tile && lit(s.tile)],
        ]);
      case "color":
        this.rn.add("ColorShader");
        return el("ColorShader", [["color", prop(this.bind(s.color))]]);
    }
  }

  colorFilter(f: ColorFilterIR): El {
    switch (f.k) {
      case "matrix":
        this.rn.add("ColorMatrix");
        return el("ColorMatrix", [["matrix", prop(this.bind(f.m))]]);
      case "blend":
        this.rn.add("BlendColor");
        return el("BlendColor", [["color", prop(this.bind(f.color))], ["mode", lit(f.mode)]]);
      case "lerp":
        this.rn.add("Lerp");
        return el("Lerp", [["t", prop(this.bind(f.t))]], [this.colorFilter(f.a), this.colorFilter(f.b)]);
      case "luma":
        this.rn.add("LumaColorFilter");
        return el("LumaColorFilter");
      case "linearToSrgb":
        this.rn.add("LinearToSRGBGamma");
        return el("LinearToSRGBGamma");
      case "srgbToLinear":
        this.rn.add("SRGBToLinearGamma");
        return el("SRGBToLinearGamma");
    }
  }

  imageFilter(f: ImageFilterIR, where: string): El {
    switch (f.k) {
      case "blur": {
        this.rn.add("Blur");
        const sx = this.bind(f.sx);
        const sy = this.bind(f.sy);
        const kx = this.keyOf(f.sx);
        const uniform =
          f.sx === f.sy || (kx !== null && kx === this.keyOf(f.sy)) || (sx.kind === "static" && sy.kind === "static" && sx.code === sy.code);
        const blur = uniform ? prop(sx) : prop(this.vec([f.sx, f.sy]));
        return el("Blur", [["blur", blur], ["mode", f.tile && lit(f.tile)]]);
      }
      case "shadow":
        this.rn.add("Shadow");
        return el("Shadow", [
          ["dx", prop(this.bind(f.dx))],
          ["dy", prop(this.bind(f.dy))],
          ["blur", prop(this.bind(f.blur))],
          ["color", prop(this.bind(f.color))],
          ["inner", f.inner ? "true" : undefined],
          ["shadowOnly", f.shadowOnly ? "true" : undefined],
        ]);
      case "offset":
        this.rn.add("Offset");
        return el("Offset", [["x", prop(this.bind(f.dx))], ["y", prop(this.bind(f.dy))]]);
      case "morphology":
        this.rn.add("Morphology");
        return el("Morphology", [["operator", lit(f.op)], ["radius", prop(this.bind(f.r))]]);
      case "displacement":
        this.rn.add("DisplacementMap");
        return el(
          "DisplacementMap",
          [["channelX", lit(f.channelX)], ["channelY", lit(f.channelY)], ["scale", prop(this.bind(f.scale))]],
          [this.shader(f.map, `${where} › displacement`)]
        );
      case "runtime":
        this.rn.add("RuntimeShader");
        return el("RuntimeShader", [["source", this.effect(f.program, where)], ["uniforms", prop(this.uniforms(f.program))]]);
    }
  }

  pathEffect(e: PathEffectIR): El | null {
    switch (e.k) {
      case "dash":
        this.rn.add("DashPathEffect");
        return el("DashPathEffect", [["intervals", prop(this.list(e.intervals))], ["phase", prop(this.bind(e.phase))]]);
      case "corner":
        this.rn.add("CornerPathEffect");
        return el("CornerPathEffect", [["r", prop(this.bind(e.r))]]);
      case "discrete":
        this.rn.add("DiscretePathEffect");
        return el("DiscretePathEffect", [["length", prop(this.bind(e.length))], ["deviation", prop(this.bind(e.deviation))], ["seed", lit(e.seed)]]);
      case "trim":
        return null; // <Path start end> — see shape()
    }
  }

  // React Native Skia composes sibling filters / effects last-first
  // (DrawingContext.materializePaint: reduceRight → MakeCompose(outer,
  // inner)); IR arrays apply in order, index 0 first — so siblings are
  // emitted reversed.
  paint(p: PaintIR, where: string): { props: [string, string | undefined][]; children: El[] } {
    const props: [string, string | undefined][] = [
      ["style", p.style === "stroke" ? '"stroke"' : undefined],
      ["color", p.color && prop(this.bind(p.color))],
      ["opacity", p.opacity && prop(this.bind(p.opacity))],
      ["strokeWidth", p.strokeWidth && prop(this.bind(p.strokeWidth))],
      ["strokeCap", p.strokeCap && lit(p.strokeCap)],
      ["strokeJoin", p.strokeJoin && lit(p.strokeJoin)],
      ["strokeMiter", p.strokeMiter === undefined ? undefined : lit(p.strokeMiter)],
      ["blendMode", p.blendMode && lit(p.blendMode)],
      ["antiAlias", p.antiAlias === undefined ? undefined : `${p.antiAlias}`],
    ];
    const children: El[] = [];
    if (p.shader) children.push(this.shader(p.shader, where));
    if (p.maskFilter) {
      this.rn.add("BlurMask");
      children.push(el("BlurMask", [["blur", prop(this.bind(p.maskFilter.sigma))], ["style", lit(p.maskFilter.style)], ["respectCTM", "true"]]));
    }
    for (const f of [...(p.colorFilters ?? [])].reverse()) children.push(this.colorFilter(f));
    for (const e of [...(p.pathEffects ?? [])].reverse()) {
      const x = this.pathEffect(e);
      if (x) children.push(x);
    }
    return { props, children };
  }

  transform(t: TransformIR | undefined): [string, string | undefined][] {
    if (!t) return [];
    if (t.matrix) return [["matrix", prop(this.bind(t.matrix))], ["origin", t.origin && prop(this.vec(t.origin))]];
    const parts: [string, Bind<number>][] = [];
    if (t.translate) parts.push(["translateX", t.translate[0]], ["translateY", t.translate[1]]);
    if (t.rotate) parts.push(["rotate", t.rotate]);
    if (t.scale) parts.push(["scaleX", t.scale[0]], ["scaleY", t.scale[1]]);
    if (t.skew) parts.push(["skewX", t.skew[0]], ["skewY", t.skew[1]]);
    const v = parts.length
      ? this.composite(
          parts.map(([, b]) => this.bind(b)),
          (c) => `[${parts.map(([k], i) => `{ ${k}: ${c[i]} }`).join(", ")}]`,
          { type: "Transforms3d" }
        )
      : undefined;
    return [["transform", v && prop(v)], ["origin", t.origin && prop(this.vec(t.origin))]];
  }

  shape(n: Extract<SkiaNode, { k: "shape" }>, where: string): El {
    const g = n.geom;
    const p = this.paint(n.paint, where);
    // RN <Path start end> trims the geometry before fill type, stroke and
    // every path effect, so trims apply first wherever they sit; several
    // compose into one interval. Any other geometry becomes its Skia path
    // (the contour start, e.g. a circle's rightmost point, is what trim
    // measures from).
    const trims = (n.paint.pathEffects ?? []).filter((e): e is Extract<PathEffectIR, { k: "trim" }> => e.k === "trim");
    const fillType: [string, string | undefined] = ["fillType", g.k === "path" && g.fillType ? lit(g.fillType) : undefined];
    if (trims.length) {
      this.rn.add("Path");
      let start: V;
      let end: V;
      if (trims.length === 1) {
        start = this.bind(trims[0].start);
        end = this.bind(trims[0].end);
      } else {
        this.helpers.add("trimSpan");
        const vs = trims.flatMap((t) => [this.bind(t.start), this.bind(t.end)]);
        start = this.composite(vs, (c) => `trimSpan([${c.join(", ")}], 0)`);
        end = this.composite(vs, (c) => `trimSpan([${c.join(", ")}], 1)`);
      }
      return el("Path", [["path", prop(this.geomPath(g))], ["start", prop(start)], ["end", prop(end)], fillType, ...p.props], p.children);
    }
    switch (g.k) {
      case "rect": {
        const tag = g.r ? "RoundedRect" : "Rect";
        this.rn.add(tag);
        return el(
          tag,
          [["x", prop(this.bind(g.x))], ["y", prop(this.bind(g.y))], ["width", prop(this.bind(g.w))], ["height", prop(this.bind(g.h))], ["r", g.r && prop(this.bind(g.r))], ...p.props],
          p.children
        );
      }
      case "circle":
        this.rn.add("Circle");
        return el("Circle", [["cx", prop(this.bind(g.cx))], ["cy", prop(this.bind(g.cy))], ["r", prop(this.bind(g.r))], ...p.props], p.children);
      case "oval":
        this.rn.add("Oval");
        return el("Oval", [["x", prop(this.bind(g.x))], ["y", prop(this.bind(g.y))], ["width", prop(this.bind(g.w))], ["height", prop(this.bind(g.h))], ...p.props], p.children);
      case "line":
        this.rn.add("Line");
        return el("Line", [["p1", prop(this.vec(g.p1))], ["p2", prop(this.vec(g.p2))], ...p.props], p.children);
      case "path":
        this.rn.add("Path");
        return el("Path", [["path", prop(this.path(g.d))], fillType, ...p.props], p.children);
      case "points":
        this.rn.add("Points");
        return el("Points", [["points", prop(this.points(g.pts))], ["mode", lit(g.mode)], ...p.props], p.children);
    }
  }

  node(n: SkiaNode, path: string): El {
    if (!this.shared.has(n)) return this.drawNode(n, path);
    const hit = this.sharedEl.get(n);
    if (hit) return hit;
    // First sight of a drawing the tree repeats: build it once as a
    // component-scope element (its hooks are already above it) and hand
    // every place that draws it a reference.
    const name = this.name("E");
    const e = this.drawNode(n, path);
    this.hooks.push(`// ${path}${n.id ? ` (${n.id})` : ""}, drawn ${this.shared.get(n)}×.\n  const ${name} = (\n${renderEl(e, "    ")}\n  );`);
    const ref = exprEl(name);
    this.sharedEl.set(n, ref);
    return ref;
  }

  private drawNode(n: SkiaNode, path: string): El {
    const where = n.id ? `${path} (${n.id})` : path;
    switch (n.k) {
      case "group": {
        const props: [string, string | El | undefined][] = [
          ...this.transform(n.transform),
          ["opacity", n.opacity && prop(this.bind(n.opacity))],
          ["blendMode", n.blendMode && lit(n.blendMode)],
          ["clip", n.clip && prop(this.clip(n.clip.geom))],
          ["invertClip", n.clip?.invert ? "true" : undefined],
        ];
        const fx = [...(n.layer?.imageFilters ?? [])].reverse().map((f) => this.imageFilter(f, where));
        const cf = [...(n.layer?.colorFilters ?? [])].reverse().map((f) => this.colorFilter(f));
        if (n.layer) {
          // The layer paint: its filters, and its blend mode — how the
          // filtered layer composites (RN saveLayer(paint)).
          const lb = n.layer.blendMode;
          const paintProps: [string, string | undefined][] = [["blendMode", lb && lb !== "srcOver" ? lit(lb) : undefined]];
          const needPaint = fx.length || cf.length || paintProps.some((p) => p[1] !== undefined);
          this.rn.add("Paint");
          props.push(["layer", needPaint ? el("Paint", paintProps, [...fx, ...cf]) : "true"]);
        }
        if (n.opacity) this.groupOpacity.push(n.opacity);
        const kids = n.children.map((c, i) => this.node(c, `${path}.children.${i}`));
        if (n.opacity) this.groupOpacity.pop();
        return el("Group", props, kids);
      }
      case "fill": {
        this.rn.add("Fill");
        const p = this.paint(n.paint, where);
        return el("Fill", p.props, p.children);
      }
      case "shape":
        return this.shape(n, where);
      case "image":
        this.rn.add("Image");
        return el("Image", [
          ["image", this.image(n.asset)],
          ["x", prop(this.bind(n.x))],
          ["y", prop(this.bind(n.y))],
          ["width", prop(this.bind(n.w))],
          ["height", prop(this.bind(n.h))],
          ["fit", lit(n.fit)],
        ]);
      case "text": {
        if (n.width) {
          // A paragraph laid out to `width`, top-left at (x, y), aligned in
          // it (RN <Paragraph>); its run takes the paint's color + opacity
          // (the planner refuses anything else on such a paint).
          this.rn.add("Paragraph");
          this.rn.add("TextAlign");
          this.rn.add("Skia");
          this.helpers.add("makeParagraph");
          const align = n.align === "center" ? "TextAlign.Center" : n.align === "right" ? "TextAlign.Right" : "TextAlign.Left";
          // RN's drawParagraph paints with the paragraph's own paint, not
          // the group's: fold the enclosing groups' opacities into the run
          // (clamped per level, as RN's opacity stack and the preview do).
          const stack = this.groupOpacity.map((b) => this.bind(b));
          const para = this.composite(
            [
              this.fonts(n.font.asset),
              this.bind(n.text),
              this.bind(n.font.size),
              n.paint.color ? this.bind(n.paint.color) : { kind: "static", code: "[0, 0, 0, 1]" },
              n.paint.opacity ? this.bind(n.paint.opacity) : { kind: "static", code: "1" },
              ...stack,
            ],
            ([f, t, s, c, o, ...g]) => {
              const clamp = (x: string) => `Math.min(1, Math.max(0, ${x}))`;
              const op = g.length ? clamp(`${g.reduce((acc, x) => clamp(`${acc} * ${x}`), "1")} * ${o}`) : o;
              return `makeParagraph(${f}, ${lit(n.font.asset)}, ${t}, ${s}, ${align}, ${c}, ${op})`;
            }
          );
          return el("Paragraph", [["paragraph", prop(para)], ["x", prop(this.bind(n.x))], ["y", prop(this.bind(n.y))], ["width", prop(this.bind(n.width))]]);
        }
        // One line with y the baseline (RN <Text>); `align` anchors the
        // run's advance at x.
        this.rn.add("Text");
        const font = this.font(n.font.asset, n.font.size);
        const p = this.paint(n.paint, where);
        let x = this.bind(n.x);
        if (n.align === "center" || n.align === "right") {
          this.helpers.add("textAdvance");
          const k = n.align === "center" ? " / 2" : "";
          x = this.composite([x, font, this.bind(n.text)], ([xx, f, t]) => `${xx} - textAdvance(${f}, ${t})${k}`);
        }
        return el("Text", [["font", prop(font)], ["text", prop(this.bind(n.text))], ["x", prop(x)], ["y", prop(this.bind(n.y))], ...p.props], p.children);
      }
      case "atlas":
        return this.atlas(n, path);
    }
  }

  // <Atlas>: the sheet is an image asset (useImage) or a sub-scene
  // rasterised once (useTexture) at the device density AK, whose sprite
  // rects × AK and xform scales ÷ AK. RSXforms: static ones are built once
  // (per AK); animated ones — or a modulation (pivots / rotate / scale) —
  // fill a useRSXformBuffer whose worklet repeats composeAtlasXforms
  // (scene-render.ts) operation for operation.
  private atlas(n: Extract<SkiaNode, { k: "atlas" }>, path: string): El {
    this.rn.add("Atlas");
    this.rn.add("rect");
    this.rn.add("Skia");
    const N = n.sprites.length;
    const tex = n.texture;
    let image: string;
    let ak = "";
    const sheetKey = tex ? JSON.stringify(tex.rect) : "";
    const sameSheet = tex ? this.sheets.get(tex.node)?.get(sheetKey) : undefined;
    if (tex && sameSheet) {
      // The same drawing over the same rect: one texture for both atlases.
      ak = this.atlasScale();
      image = sameSheet;
    } else if (tex) {
      ak = this.atlasScale();
      this.rn.add("useTexture");
      const refs = new Set<string>();
      const outerRefs = this.renderRefs;
      const outerOpacity = this.groupOpacity;
      this.renderRefs = refs;
      this.groupOpacity = []; // the sheet renders on its own, not under our groups
      const inner = this.node(tex.node, `${path}.texture.node`);
      this.renderRefs = outerRefs;
      this.groupOpacity = outerOpacity;
      for (const r of refs) outerRefs?.add(r);
      const [x, y, w, h] = tex.rect;
      const size = this.name("SZ");
      this.hooks.push(`const ${size} = React.useMemo(() => ({ width: Math.ceil(${lit(w)} * ${ak}), height: Math.ceil(${lit(h)} * ${ak}) }), [${ak}]);`);
      const sheet = renderEl(el("Group", [["transform", `[{ scale: ${ak} }, { translateX: ${lit(-x)} }, { translateY: ${lit(-y)} }]`]], [inner]), "    ");
      image = this.name("TEX");
      this.hooks.push(`// ${path}: the sprite sheet, rendered once (and again when its assets land).\n  const ${image} = useTexture(\n${sheet},\n    ${size},\n    [${[size, ...refs].join(", ")}]\n  );`);
      if (!this.sheets.has(tex.node)) this.sheets.set(tex.node, new Map());
      this.sheets.get(tex.node)!.set(sheetKey, image);
    } else {
      image = this.image(n.asset);
    }

    // Sprites: identical rects (Copy to Points' one instance) compactly.
    const same = n.sprites.every((s) => s.every((v, i) => v === n.sprites[0][i]));
    const rectCode = (r: [number, number, number, number]) =>
      ak ? `rect(${r.map((v) => (v === 0 ? "0" : `${lit(v)} * ${ak}`)).join(", ")})` : `rect(${r.map(lit).join(", ")})`;
    const spriteList = same && N > 1 ? `Array.from({ length: ${N} }, () => ${rectCode(n.sprites[0])})` : `[${n.sprites.map(rectCode).join(", ")}]`;
    let sprites: string;
    if (ak) {
      sprites = this.name("SP");
      this.hooks.push(`const ${sprites} = React.useMemo(() => ${spriteList}, [${ak}]);`);
    } else {
      sprites = this.name("K");
      this.consts.push(`const ${sprites} = ${spriteList};`);
    }

    const div = (code: string) => (ak ? `${code} / ${ak}` : code);
    const xv = this.bind(n.xforms);
    const mod = !!(n.rotate || n.scale);
    const pv = mod && n.pivots ? this.bind(n.pivots) : null;
    const rv = n.rotate ? this.bind(n.rotate) : null;
    const sv = n.scale ? this.bind(n.scale) : null;
    const staticOf = <T,>(b: Bind<T> | undefined): T | undefined => {
      if (!b) return undefined;
      const p = this.plan.bindFor.get(b)?.plan as { kind?: string; value?: T } | undefined;
      return p?.kind === "static" ? p.value : b.v;
    };
    let xforms: string;
    if (![xv, pv, rv, sv].some((v) => v?.kind === "anim")) {
      // Everything static: compose at export, divide by AK at run time.
      const data = composeAtlasXforms(staticOf(n.xforms) ?? [], mod ? { pivots: staticOf(n.pivots), rotate: staticOf(n.rotate), scale: staticOf(n.scale) } : {});
      const dataName = this.name("XD");
      this.consts.push(`// ${path}: ${N} RSXforms (scos, ssin, tx, ty), toolbox px.\nconst ${dataName} = ${lit(data)};`);
      const build = `Array.from({ length: ${N} }, (_, i) => Skia.RSXform(${div(`${dataName}[i * 4]`)}, ${div(`${dataName}[i * 4 + 1]`)}, ${dataName}[i * 4 + 2], ${dataName}[i * 4 + 3]))`;
      xforms = this.name("XF");
      if (ak) this.hooks.push(`const ${xforms} = React.useMemo(() => ${build}, [${ak}]);`);
      else this.consts.push(`const ${xforms} = ${build};`);
    } else {
      this.rn.add("useRSXformBuffer");
      // Static parts as module data the worklet captures.
      const data = (v: V, b: Bind<number[]> | undefined, label: string) => {
        if (v.kind === "anim") return v.inner;
        const name = this.name(label);
        this.consts.push(`const ${name} = ${lit(staticOf(b) ?? [])};`);
        return name;
      };
      const A = data(xv, n.xforms, "XA");
      let lines = [`const A = ${A};`];
      if (mod) {
        const P = data(pv!, n.pivots, "XP");
        const r = rv ? (rv.kind === "anim" ? rv.inner : rv.kind === "static" ? rv.code : "0") : "0";
        const s = sv ? (sv.kind === "anim" ? sv.inner : sv.kind === "static" ? sv.code : "1") : "1";
        let M: string;
        if (rv?.kind === "anim" || sv?.kind === "anim") {
          M = this.name("XM");
          this.rea.add("useDerivedValue");
          this.hooks.push(`const ${M} = useDerivedValue(() => [Math.cos(${r}) * ${s}, Math.sin(${r}) * ${s}]);`);
          M = `${M}.value`;
        } else {
          M = this.name("XM");
          this.consts.push(`const ${M} = [Math.cos(${r}) * ${s}, Math.sin(${r}) * ${s}];`);
        }
        lines = [
          ...lines,
          `const P = ${P};`,
          `const M = ${M};`,
          `const c = M[0];`,
          `const d = M[1];`,
          `const a = A[i * 4];`,
          `const b = A[i * 4 + 1];`,
          `const tx = A[i * 4 + 2];`,
          `const ty = A[i * 4 + 3];`,
          `const px = P[i * 2];`,
          `const py = P[i * 2 + 1];`,
          `xf.set(${div("(c * a - d * b)")}, ${div("(d * a + c * b)")}, px + c * (tx - px) - d * (ty - py), py + d * (tx - px) + c * (ty - py));`,
        ];
      } else {
        lines.push(`xf.set(${div("A[i * 4]")}, ${div("A[i * 4 + 1]")}, A[i * 4 + 2], A[i * 4 + 3]);`);
      }
      xforms = this.name("XF");
      this.hooks.push(`const ${xforms} = useRSXformBuffer(${N}, (xf, i) => {\n    "worklet";\n${lines.map((l) => `    ${l}`).join("\n")}\n  });`);
    }
    return el("Atlas", [["image", image], ["sprites", sprites], ["transforms", xforms]]);
  }
}

// ---- timeline.ts ---------------------------------------------------------------------------

const SERIES_SOURCE = {
  index:
    `function seriesIndex(f: number[], frame: number): number {\n  "worklet";\n  let lo = 0;\n  let hi = f.length - 1;\n  if (frame >= f[hi]) return hi;\n  while (hi - lo > 1) {\n    const mid = (lo + hi) >> 1;\n    if (f[mid] <= frame) lo = mid;\n    else hi = mid;\n  }\n  return lo;\n}\n`,
  step:
    `export function seriesStep<T>(s: Series<T>, frame: number): T {\n  "worklet";\n  return s.v[seriesIndex(s.f, frame)];\n}\n`,
  lerp:
    `export function seriesLerp(s: Series<number>, frame: number): number {\n  "worklet";\n  const i = seriesIndex(s.f, frame);\n  const a = s.v[i];\n  if (i >= s.f.length - 1 || frame <= s.f[i]) return a;\n  const b = s.v[i + 1];\n  if (a === b) return a;\n  return a + (b - a) * ((frame - s.f[i]) / (s.f[i + 1] - s.f[i]));\n}\n`,
  lerpN:
    `export function seriesLerpN(s: Series<number[]>, frame: number): number[] {\n  "worklet";\n  const i = seriesIndex(s.f, frame);\n  const a = s.v[i];\n  if (i >= s.f.length - 1 || frame <= s.f[i]) return a;\n  const b = s.v[i + 1];\n  const u = (frame - s.f[i]) / (s.f[i + 1] - s.f[i]);\n  return a.map((x, k) => (x === b[k] ? x : x + (b[k] - x) * u));\n}\n`,
};

function emitTimeline(plan: ScenePlan, em: SceneEmitter, supplied?: Map<string, string>): { text: string; fields: number; procedural: ProceduralValue[] } {
  const decls: string[] = [];
  const fields: string[] = [];
  const procedural: ProceduralValue[] = [];
  let usesTick = false;
  let usesTrack = false;
  let usesFrame = false;
  const series = new Set<keyof typeof SERIES_SOURCE>();
  const shared = new Map<string, number>();
  for (const [id, key] of em.keys) if (id !== key) shared.set(key, (shared.get(key) ?? 0) + 1);
  for (const b of plan.binds) {
    if (em.keys.get(b.id) !== b.id) continue; // reads another bind's key
    if (supplied?.has(b.id)) continue; // the driver's
    const p = b.plan;
    const more = shared.get(b.id);
    const note = `// ${b.path}${more ? ` (+${more} more)` : ""}: ${p.kind === "refused" ? p.reason : p.from}`;
    if (p.kind === "expr") {
      // A compiled procedural driver (procedural.ts, spec §3.5e).
      usesTick = true;
      procedural.push({ key: b.id, program: p.program, from: p.from });
      fields.push(`    ${b.id}: ${proceduralFnName(b.id)}(tick)${p.scale === undefined ? "" : ` * ${lit(p.scale)}`}, // ${p.from}`);
    } else if (p.kind === "track") {
      usesTick = true;
      usesTrack = true;
      const ts = b.role === "array" && p.pick === undefined && p.tracks.length === 1 ? "number[]" : "number";
      // (A BindRef.scale rides on the track: the runtime multiplies.)
      if (p.tracks.length === 1) {
        decls.push(`${note}\nconst T_${b.id}: TimelineTrack = ${JSON.stringify(p.tracks[0])};`);
        const read = p.pick === undefined ? `evaluateTrack(T_${b.id}, tick) as ${ts}` : `(evaluateTrack(T_${b.id}, tick) as number[])[${p.pick}]`;
        fields.push(`    ${b.id}: ${read}, // ${p.from}`);
      } else {
        p.tracks.forEach((t, i) => decls.push(`${i === 0 ? `${note}\n` : ""}const T_${b.id}_${i}: TimelineTrack = ${JSON.stringify(t)};`));
        fields.push(`    ${b.id}: [${p.tracks.map((_, i) => `evaluateTrack(T_${b.id}_${i}, tick) as number`).join(", ")}], // ${p.from}`);
      }
    } else if (p.kind === "clock") {
      fields.push(`    ${b.id}: seconds, // ${p.from}`);
    } else if (p.kind === "sampled" && b.role !== "path") {
      usesFrame = true;
      const mode = seriesMode(b as PlannedBind & { plan: { kind: "sampled" } });
      const s = compress(p.values, mode === "step" ? "step" : "lerp");
      const t = b.role === "number" ? "number" : b.role === "string" ? "string" : "number[]";
      decls.push(`${note}\nconst S_${b.id}: Series<${t}> = ${JSON.stringify(s)};`);
      series.add("index");
      series.add(mode);
      fields.push(`    ${b.id}: ${mode === "lerp" ? "seriesLerp" : mode === "lerpN" ? "seriesLerpN" : "seriesStep"}(S_${b.id}, frame), // ${p.from}`);
    }
  }
  if (em.timelineDecls.length) {
    series.add("index");
    series.add("step");
  }
  const helperOrder: (keyof typeof SERIES_SOURCE)[] = ["index", "step", "lerp", "lerpN"];
  const rtImports = usesTrack || (usesTick && !procedural.length) ? "evaluateTrack, ticksAt, type TimelineTrack" : "ticksAt";
  const text =
    HEADER("the animation timeline") +
    `\nimport { ${rtImports} } from "./toolbox-timeline";\n` +
    (procedural.length ? `import { ${procedural.map((v) => proceduralFnName(v.key)).join(", ")} } from "./procedural";\n` : "") +
    `\nexport const NAME = ${JSON.stringify(plan.name)};\n` +
    timelineConstSource(plan.timeline) +
    `\n// Toolbox canvas px — the scene's own coordinate space.\nexport const CANVAS = { width: ${plan.canvas.width}, height: ${plan.canvas.height} } as const;\n` +
    `\n// Fractional toolbox frame at \`seconds\` (frame-aligned times are exact).\n` +
    `export function frameAt(seconds: number): number {\n  "worklet";\n  return ticksAt(seconds, TIMELINE.fps, TIMELINE.ticksPerFrame) / TIMELINE.ticksPerFrame;\n}\n` +
    (series.size
      ? `\n// A sampled value: the producer's value at frames \`f\` (ascending from 0).\n// Interpolating series keep both ends of each run of equal values, stepped\n// ones only its start, so both read back exactly at every frame.\nexport interface Series<T> {\n  f: number[];\n  v: T[];\n}\n\n` +
        helperOrder.filter((h) => series.has(h)).map((h) => SERIES_SOURCE[h]).join("\n")
      : "") +
    (decls.length ? `\n${decls.join("\n\n")}\n` : "") +
    (em.timelineDecls.length ? `\n${em.timelineDecls.join("\n\n")}\n` : "") +
    `\n// Every animated bind at \`seconds\` on the toolbox timeline, keyed by bind id\n// (manifest.json maps ids to IR paths). Animated path geometry is not here:\n// the component reads the pre-parsed PATH_* series itself.\n` +
    `export function sampleBinds(seconds: number) {\n  "worklet";\n` +
    (usesTick || usesFrame ? `  const tick = ticksAt(seconds, TIMELINE.fps, TIMELINE.ticksPerFrame);\n` : "") +
    (usesFrame ? `  const frame = tick / TIMELINE.ticksPerFrame;\n` : "") +
    (fields.length ? `  return {\n${fields.join("\n")}\n  };\n}\n` : `  return {};\n}\n`);
  return { text, fields: fields.length, procedural };
}

// ---- the bundle ------------------------------------------------------------------------------

// `segments`: the composition's markers on this timeline (exportSegments);
// default none — SEGMENTS ships empty. `driver`: see SceneDriver.
export function emitSceneBundle(
  plan: ScenePlan,
  runtimeSource: string,
  segments: ExportSegments = NO_EXPORT_SEGMENTS,
  driver?: SceneDriver
): Record<string, string> {
  const em = new SceneEmitter(plan);
  const files: Record<string, string> = {};

  const content: El[] = [];
  if (plan.scene.background) {
    em.rn.add("Fill");
    content.push(el("Fill", [["color", lit(plan.scene.background)]]));
  }
  content.push(em.node(plan.scene.root, "root"));
  const body = renderEl(
    el("Group", [["transform", "[{ scaleX: width / CANVAS.width }, { scaleY: height / CANVAS.height }]"]], content),
    "    "
  );

  // ---- effects.ts
  files["effects.ts"] =
    HEADER("the scene's SkSL programs") +
    `\n// Each program exactly as toolbox compiled it with CanvasKit ${CANVASKIT_VERSION}.\n` +
    (em.effects.length
      ? em.effects
          .map(
            (e, i) =>
              `\n// Program ${i}: ${e.where.join("; ")}${e.fused.length ? `\n// fused: ${e.fused.join(", ")}` : ""}\nexport const SKSL_${i} = ${JSON.stringify(e.sksl)};\n`
          )
          .join("")
      : `\nexport {};\n`);

  // ---- assets.ts + bytes (asset-bundle.ts: the same rule the planner's
  // "not bundled" warnings used)
  const assetEntries = writeAssetFiles(plan.assetUses ?? plan.assets.map((asset) => ({ asset, owners: [] })), plan.assetBytes, files);
  files["assets.ts"] = assetSourcesModule(HEADER("the scene's assets"), "the scene draws", assetEntries);

  // ---- timeline.ts
  const timeline = emitTimeline(plan, em, driver?.supplied);
  files["timeline.ts"] = timeline.text;
  files["toolbox-timeline.ts"] = runtimeSource;
  if (timeline.procedural.length) files["procedural.ts"] = emitProceduralModule(timeline.procedural);

  // ---- ToolboxScene.tsx
  const hooks = [...em.hooks];
  if (em.needF) {
    em.rea.add("useDerivedValue");
    em.timelineImports.add("frameAt");
    hooks.unshift(`const F = useDerivedValue(() => frameAt(time.value));`);
  }
  if (em.needB) {
    em.rea.add("useDerivedValue");
    if (!driver || timeline.fields) em.timelineImports.add("sampleBinds");
    if (!driver) hooks.unshift(`const B = useDerivedValue(() => sampleBinds(time.value));`);
    else {
      const own = [...driver.supplied].map(([k, e]) => `${k}: ${e},`);
      const parts = [...(timeline.fields ? ["...sampleBinds(time.value),"] : []), ...own];
      hooks.unshift(`const B = useDerivedValue(() => ({\n${parts.map((p) => `    ${p}`).join("\n")}\n  }));`);
    }
  }
  if (driver) hooks.unshift(...driver.prelude);
  em.rn.add("Canvas");
  const helperSrc: Record<string, string> = {
    makeEffect:
      `function makeEffect(sksl: string, n: number) {\n  const effect = Skia.RuntimeEffect.Make(sksl);\n  if (!effect) throw new Error(\`toolbox export: SkSL program \${n} did not compile on this Skia build\`);\n  return effect;\n}\n`,
    parsePath:
      `function parsePath(d: string) {\n  const path = Skia.Path.MakeFromSVGString(d);\n  if (!path) throw new Error(\`toolbox export: bad path data "\${d.slice(0, 40)}"\`);\n  return path;\n}\n`,
    toPoints:
      `// Flat x,y pairs → points.\nfunction toPoints(xy: number[]) {\n  "worklet";\n  const out = [];\n  for (let i = 0; i + 1 < xy.length; i += 2) out.push(vec(xy[i], xy[i + 1]));\n  return out;\n}\n`,
    textAdvance:
      `// The run's advance width (what <Text> alignment anchors).\nfunction textAdvance(font: SkFont | null, text: string) {\n  "worklet";\n  if (!font) return 0;\n  return font.getGlyphWidths(font.getGlyphIDs(text)).reduce((a, b) => a + b, 0);\n}\n`,
    makeParagraph:
      `// One run in the scene font, its paint the text's color × opacity.\nfunction makeParagraph(\n  fonts: SkTypefaceFontProvider | null,\n  family: string,\n  text: string,\n  size: number,\n  align: TextAlign,\n  color: number[],\n  opacity: number\n) {\n  "worklet";\n  if (!fonts) return null;\n  const paint = Skia.Paint();\n  paint.setColor(Skia.Color(color));\n  paint.setAlphaf(color[3] * opacity);\n  const style = { fontFamilies: [family], fontSize: size };\n  return Skia.ParagraphBuilder.Make({ textAlign: align, textStyle: style }, fonts).pushStyle(style, paint).addText(text).build();\n}\n`,
    trimSpan:
      `// Several trims compose by length fraction, each over what the previous kept.\nfunction trimSpan(t: number[], which: number) {\n  "worklet";\n  let s = 0;\n  let e = 1;\n  for (let i = 0; i + 1 < t.length; i += 2) {\n    const span = e - s;\n    const ns = s + Math.min(1, Math.max(0, t[i])) * span;\n    e = s + Math.min(1, Math.max(0, t[i + 1])) * span;\n    s = ns;\n  }\n  return which === 0 ? s : e;\n}\n`,
  };
  if (em.helpers.has("makeEffect") || em.helpers.has("parsePath")) em.rn.add("Skia");
  if (em.helpers.has("textAdvance")) em.rnTypes.add("SkFont");
  if (em.helpers.has("makeParagraph")) em.rnTypes.add("SkTypefaceFontProvider");
  em.rnTypes.add("CanvasRef");
  const rnNames = [...em.rn].sort((a, b) => a.localeCompare(b));
  const rnTypes = [...em.rnTypes].sort((a, b) => a.localeCompare(b)).map((t) => `type ${t}`);
  const reaNames = [...em.rea].sort((a, b) => a.localeCompare(b));
  const tlNames = [...em.timelineImports].sort((a, b) => a.localeCompare(b));
  const usesTime = em.needB || em.needF;
  const reaImports = driver ? reaNames : [...reaNames, "type SharedValue"];
  const prop = driver ? driver.prop : "time";
  files["ToolboxScene.tsx"] =
    HEADER("the React Native Skia scene") +
    `\nimport React from "react";\n` +
    (em.needPixelRatio ? `import { PixelRatio } from "react-native";\n` : "") +
    `import {\n  ${[...rnNames, ...rnTypes].join(",\n  ")},\n} from "react-native-skia";\n` +
    (reaImports.length ? `import { ${reaImports.join(", ")} } from "react-native-reanimated";\n` : "") +
    (em.effects.length ? `import { ${em.effects.map((_, i) => `SKSL_${i}`).join(", ")} } from "./effects";\n` : "") +
    (assetEntries.length ? `import { ASSET_SOURCES } from "./assets";\n` : "") +
    `import { ${tlNames.join(", ")} } from "./timeline";\n` +
    (driver?.imports.length ? `${driver.imports.join("\n")}\n` : "") +
    (em.helpers.size ? `\n${["makeEffect", "parsePath", "toPoints", "textAdvance", "makeParagraph", "trimSpan"].filter((h) => em.helpers.has(h)).map((h) => helperSrc[h]).join("\n")}` : "") +
    (em.consts.length ? `\n${em.consts.join("\n")}\n` : "") +
    `\nexport interface ToolboxSceneGroupProps {\n${driver ? driver.propDecl : "  // Seconds on the toolbox timeline (see useToolboxClock).\n  time: SharedValue<number>;\n"}  // The size to draw at, in points; the scene is authored at CANVAS px.\n  width: number;\n  height: number;\n}\n` +
    `\nexport interface ToolboxSceneProps extends ToolboxSceneGroupProps {\n  canvasRef?: React.Ref<CanvasRef>;\n}\n` +
    `\n// The scene as one Group, scaled from toolbox canvas px to width × height:\n// drop it into your own <Canvas> to stack it with other content.\n` +
    `export function ToolboxSceneGroup({ ${driver || usesTime ? `${prop}, ` : ""}width, height }: ToolboxSceneGroupProps) {\n` +
    (hooks.length ? hooks.map((h) => `  ${h}`).join("\n") + "\n" : "") +
    `  return (\n${body}\n  );\n}\n` +
    `\nexport function ToolboxScene({ ${prop}, width, height, canvasRef }: ToolboxSceneProps) {\n  return (\n    <Canvas ref={canvasRef} style={{ width, height }}>\n      <ToolboxSceneGroup ${prop}={${prop}} width={width} height={height} />\n    </Canvas>\n  );\n}\n` +
    (driver ? "" : toolboxClockSource());

  // ---- toolbox-clock.ts
  files["toolbox-clock.ts"] = clockModuleSource(plan.timeline, segments, HEADER("the playback clock and its segments"));

  // ---- manifest.json
  const durationSec = durationSecOf(plan.timeline);
  files["manifest.json"] =
    JSON.stringify(
      {
        format: SKIA_SCENE_EXPORT_FORMAT,
        kind: "scene",
        name: plan.name,
        exportedBy: "toolbox Skia Canvas",
        irVersion: SKIA_IR_VERSION,
        canvaskit: CANVASKIT_VERSION,
        reactNativeSkia: RN_SKIA_VERSION,
        // Every program converts its sRGB math to the canvas's color space
        // (native drawing is Skia's to convert): same colors on sRGB and P3.
        colorManaged: em.effects.every((e) => isColorManagedSksl(e.sksl)),
        canvas: plan.canvas,
        timeline: { fps: plan.timeline.fps, ticksPerFrame: plan.timeline.ticksPerFrame, durationTicks: plan.timeline.durationTicks, durationSec, frames: plan.timeline.frames },
        // Named segments (toolbox-clock.ts SEGMENTS) and marker times.
        ...manifestSegments(segments),
        sampledFrames: plan.sampledFrames,
        // React Native Skia web (CanvasKit) lacks runtime image filters and
        // path-effect composition; the warnings say which node needs them.
        webPlayable: !plan.warnings.some((w) => w.includes("not playable on React Native Skia web")),
        // Every bind by kind; only the animated ones are listed below
        // (`sample` = the sampleBinds key it reads; path geometry reads the
        // PATH_<sample> series instead).
        bindCounts: plan.binds.reduce<Record<string, number>>((m, b) => ({ ...m, [b.plan.kind]: (m[b.plan.kind] ?? 0) + 1 }), {}),
        binds: plan.binds.flatMap((b) => {
          const p = b.plan;
          const base = { id: b.id, path: b.path, kind: p.kind, sample: em.keys.get(b.id) };
          switch (p.kind) {
            case "track":
              return [{ ...base, from: p.from, keys: p.tracks.reduce((n, t) => n + t.keys.length, 0), ...(p.tracks[0].scale === undefined ? {} : { scale: p.tracks[0].scale }) }];
            case "clock":
              return [{ ...base, from: p.from }];
            case "sampled":
              return [{ ...base, role: b.role, from: p.from, distinct: new Set(p.values.map((v) => JSON.stringify(v))).size }];
            case "expr":
              // Compiled from a driver subgraph: procedural.ts P_<sample>.
              return [{ ...base, from: p.from, procedural: proceduralManifest(p.program), ...(p.scale === undefined ? {} : { scale: p.scale }) }];
            default:
              return [];
          }
        }),
        programs: em.effects.map((e, i) => ({ id: `SKSL_${i}`, usedBy: e.where, fused: e.fused })),
        // Every asset with its file, size and whether its bytes shipped.
        assets: assetEntries.map(manifestAsset),
        warnings: plan.warnings,
      },
      null,
      2
    ) + "\n";

  files["index.ts"] =
    HEADER("barrel") +
    `\nexport { ToolboxScene, ToolboxSceneGroup } from "./ToolboxScene";\n` +
    CLOCK_BARREL +
    `export { NAME, CANVAS, TIMELINE, frameAt, sampleBinds } from "./timeline";\n`;

  return files;
}
