// emitSceneBundle — the files a React Native Skia app drops in to play a
// Skia layer's scene exactly as toolbox renders it
// (specdocs/101326_skia-target.md §3.4–3.5a).
//
//   ToolboxScene.tsx    <ToolboxScene time width height /> (its own Canvas)
//                       and <ToolboxSceneGroup> (the same content, to stack
//                       inside your Canvas); re-exports useToolboxClock
//   toolbox-clock.ts    useToolboxClock() + controls, SEGMENTS, MARKERS
//                       (segments.ts)
//   timeline.ts         track + sampled data, sampleBinds(seconds) — one
//                       worklet that evaluates every animated bind
//   toolbox-timeline.ts the keyframe evaluator (src/lib/skia-export/runtime)
//   procedural.ts       only with procedural drivers (spec §3.5e): one
//                       worklet P_<bind>(tick) per expr bind sampleBinds reads
//   effects.ts          the SkSL of every runtime program, deduped
//   assets.ts           require() of every asset the scene draws, by IR id
//   assets/*.b64        bytes the exporter had (SkiaExportRequest.assets,
//                       resolved through the URL → bytes seam before the
//                       export, or data: URLs) + licence texts; manifest.json
//                       lists every asset, the rest with their editor URLs
//                       (asset-bundle.ts)
//   manifest.json       format 3, kind "scene": binds, programs, assets,
//                       segments
//   index.ts            barrel
//
// Reanimated wiring. The whole scene reads ONE derived value, B =
// sampleBinds(time): a plain prop takes `select(B, "b3")` (no mapper of its
// own), and only props that compose several values into one object
// (transforms, uniforms, gradient colors, Skia rects/paths) get their own
// useDerivedValue, and only when one of their inputs animates. Static values
// are inlined; static Skia objects are built once at module scope.
//
// Animated path geometry (a generator's `d`, sampled per frame) ships as
// SVG strings at the frames where it changes, pre-parsed once at module
// scope. When every frame has the same verb structure the component plays
// usePathInterpolation over them (one native interpolate per UI frame,
// smooth between toolbox frames, exact on them); otherwise it steps to the
// frame's pre-parsed path (one array read). No per-frame SVG parsing.

