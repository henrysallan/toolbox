// Procedural programs → worklet TypeScript (`procedural.ts` in a bundle;
// specdocs/101326_skia-target.md §3.5e). One function per exported value,
// `P_<key>(tick)`, plus exactly the helpers they call — each the engine's
// own arithmetic, transcribed operation for operation (engine/easing.ts,
// float-curve.ts, expression.ts, random.ts), so a worklet returns the
// double the evaluator computes. check:skia-procedural holds every helper
// and every fixture bit-identical to the engine at every frame, as
// TypeScript and as the worklets Babel plugin's output.
//
// Worklets capture their callees when created (the Babel plugin turns each
// into a const): every function here calls only functions declared ABOVE it
// — helpers in dependency order, data constants, then the value functions.

import { ENV_HELPERS, helperName, MATH_FNS, MATH_VARIADIC, type PExpr, type ProcProgram } from "./ir";

const HEADER =
  `// Generated by toolbox — the procedural drivers (Expression / LFO / Math / Scene Time /\n` +
  `// Random / Constant / Animated Value), compiled to worklets of the toolbox tick.\n` +
  `// Do not edit by hand: change the driver nodes and export again.\n`;

// ---- helper sources (engine code, verbatim) ----------------------------------------------------

const EASING_BASES: Record<string, string> = {
  Quad: `return t * t;`,
  Cubic: `return t * t * t;`,
  Quart: `return t * t * t * t;`,
  Quint: `return t * t * t * t * t;`,
  Sine: `return 1 - Math.cos((t * Math.PI) / 2);`,
  Expo: `return t <= 0 ? 0 : Math.pow(2, 10 * (t - 1));`,
  Circ: `return 1 - Math.sqrt(Math.max(0, 1 - t * t));`,
  Back: `return (1.70158 + 1) * t * t * t - 1.70158 * t * t;`,
  Elastic: `if (t <= 0) return 0;\n  if (t >= 1) return 1;\n  const c4 = (2 * Math.PI) / 3;\n  return -Math.pow(2, 10 * t - 10) * Math.sin((t * 10 - 10.75) * c4);`,
  // inBounce = 1 - outBounce(1 - t); outBounce first (below).
  Bounce: `return 1 - tbxOutBounce(1 - t);`,
};
const OUT_BOUNCE = `function tbxOutBounce(t: number): number {\n  "worklet";\n  const n1 = 7.5625;\n  const d1 = 2.75;\n  if (t < 1 / d1) return n1 * t * t;\n  if (t < 2 / d1) {\n    const u = t - 1.5 / d1;\n    return n1 * u * u + 0.75;\n  }\n  if (t < 2.5 / d1) {\n    const u = t - 2.25 / d1;\n    return n1 * u * u + 0.9375;\n  }\n  const u = t - 2.625 / d1;\n  return n1 * u * u + 0.984375;\n}`;

// engine/easing.ts EASINGS[name] as a function body of `t` plus the bases it
// needs. Names it doesn't define play linear (applyEasing's fallback).
function easingBody(name: string): { body: string; bases: string[] } {
  switch (name) {
    case "step":
      return { body: `return t < 1 ? 0 : 1;`, bases: [] };
    case "smoothstep":
      return { body: `return t * t * (3 - 2 * t);`, bases: [] };
    case "smootherstep":
      return { body: `return t * t * t * (t * (t * 6 - 15) + 10);`, bases: [] };
    case "ease-in":
      return { body: `return tbxInQuad(t);`, bases: ["Quad"] };
    case "ease-out":
      return { body: `return 1 - tbxInQuad(1 - t);`, bases: ["Quad"] };
    case "ease-in-out":
      return { body: `return t < 0.5 ? tbxInQuad(2 * t) / 2 : 1 - tbxInQuad(2 * (1 - t)) / 2;`, bases: ["Quad"] };
  }
  const m = /^ease-(in|out|in-out)-(cubic|quart|quint|sine|expo|circ|back|elastic|bounce)$/.exec(name);
  if (m) {
    const fam = m[2][0].toUpperCase() + m[2].slice(1);
    const f = `tbxIn${fam}`;
    const body = m[1] === "in" ? `return ${f}(t);` : m[1] === "out" ? `return 1 - ${f}(1 - t);` : `return t < 0.5 ? ${f}(2 * t) / 2 : 1 - ${f}(2 * (1 - t)) / 2;`;
    return { body, bases: [fam] };
  }
  return { body: `return t;`, bases: [] };
}

export const easeFnName = (name: string) => `tbxEase_${name.replace(/[^A-Za-z0-9]/g, "_")}`;

const fn = (sig: string, body: string) => `function ${sig} {\n  "worklet";\n  ${body}\n}`;

const FIXED_HELPERS: Record<string, string> = {
  toNum: fn(`tbxNum(v: number): number`, `return Number.isFinite(v) ? v : 0;`),
  rand:
    `// expression.ts mulberry32, one draw from the state after its\n// \`a = (a + 0x6d2b79f5) | 0\` step.\n` +
    fn(`tbxRand(a: number): number`, `let t = Math.imul(a ^ (a >>> 15), 1 | a);\n  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;\n  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;`),
  seed32: `// The Expression RNG's seed for one evaluation: hash(nodeId) ^ ((frame >>> 0) + 0x9e3779b9).\n` + fn(`tbxSeed32(h: number, frame: number): number`, `return h ^ ((frame >>> 0) + 0x9e3779b9);`),
  lfoPhase:
    `// lfo.ts: the unit phase ((t · frequency + phase) % 1 + 1) % 1, t = tick / (ticksPerFrame · fps).\n` +
    fn(`tbxLfoPhase(tick: number, tps: number, f: number, ph: number): number`, `const raw = (tick / tps) * f + ph;\n  return ((raw % 1) + 1) % 1;`),
  hash01:
    `// random.ts hash01.\n` +
    fn(
      `tbxHash01(seed: number, frame: number, salt: number): number`,
      `let h = (seed | 0) ^ Math.imul(frame | 0, 0x27d4eb2d) ^ Math.imul(salt | 0, 0x165667b1);\n  h = Math.imul(h ^ (h >>> 15), 0x735a2d97);\n  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);\n  h ^= h >>> 16;\n  return (h >>> 0) / 4294967296;`
    ),
  monotone:
    `// engine/float-curve.ts evalMonotoneCubic (points + Fritsch–Carlson tangents).\n` +
    `interface TbxCurve {\n  x: number[];\n  y: number[];\n  m: number[];\n}\n` +
    fn(
      `tbxMonotone(c: TbxCurve, x: number): number`,
      `const n = c.x.length;\n  if (n === 0) return 0;\n  if (n === 1) return c.y[0];\n  if (x <= c.x[0]) return c.y[0];\n  if (x >= c.x[n - 1]) return c.y[n - 1];\n  let i = 0;\n  for (; i < n - 1; i++) {\n    if (x <= c.x[i + 1]) break;\n  }\n  const x0 = c.x[i];\n  const x1 = c.x[i + 1];\n  const h = x1 - x0;\n  if (h === 0) return c.y[i];\n  const t = (x - x0) / h;\n  const t2 = t * t;\n  const t3 = t2 * t;\n  const h00 = 2 * t3 - 3 * t2 + 1;\n  const h10 = t3 - 2 * t2 + t;\n  const h01 = -2 * t3 + 3 * t2;\n  const h11 = t3 - t2;\n  return h00 * c.y[i] + h10 * h * c.m[i] + h01 * c.y[i + 1] + h11 * h * c.m[i + 1];`
    ),
  curve:
    `// engine/easing.ts applyEasingOrCurve, the custom route.\n` +
    fn(`tbxCurve(c: TbxCurve, t: number, intensity: number): number`, `const tt = Math.max(0, Math.min(1, t));\n  const eased = tbxMonotone(c, tt);\n  return tt + intensity * (eased - tt);`),
};

// Helper id → its source, in a dependency-respecting order.
function helperSources(ids: Set<string>): string[] {
  const out: string[] = [];
  const done = new Set<string>();
  const add = (id: string, src: string) => {
    if (done.has(id)) return;
    done.add(id);
    out.push(src);
  };
  for (const id of ["toNum", "rand", "seed32", "hash01", "lfoPhase"]) if (ids.has(id)) add(id, FIXED_HELPERS[id]);
  for (const e of Object.keys(ENV_HELPERS)) if (ids.has(e)) add(e, ENV_HELPERS[e].src);
  // Easings: bases (outBounce before inBounce), then one applyEasing per name.
  const names = [...ids].filter((x) => x.startsWith("ease:")).map((x) => x.slice(5));
  const bases = new Set(names.flatMap((n) => easingBody(n).bases));
  if (bases.has("Bounce")) add("outBounce", OUT_BOUNCE);
  for (const b of Object.keys(EASING_BASES)) if (bases.has(b)) add(`in${b}`, fn(`tbxIn${b}(t: number): number`, EASING_BASES[b]));
  for (const name of names) {
    const { body } = easingBody(name);
    const curve = `tbxE_${name.replace(/[^A-Za-z0-9]/g, "_")}`;
    add(
      `ease:${name}`,
      `// engine/easing.ts EASINGS["${name}"], then applyEasing (clamp, intensity blend).\n` +
        fn(`${curve}(t: number): number`, body) +
        "\n\n" +
        fn(`${easeFnName(name)}(t: number, intensity: number): number`, `const tt = Math.max(0, Math.min(1, t));\n  const eased = ${curve}(tt);\n  return tt + intensity * (eased - tt);`)
    );
  }
  if (ids.has("curve")) {
    add("monotone", FIXED_HELPERS.monotone);
    add("curve", FIXED_HELPERS.curve);
  }
  return out;
}

// ---- printing ------------------------------------------------------------------------------------

function num(v: number): string {
  if (Number.isNaN(v)) return "NaN";
  if (v === Infinity) return "Infinity";
  if (v === -Infinity) return "(-Infinity)";
  if (Object.is(v, -0)) return "(-0)";
  return v < 0 ? `(${String(v)})` : String(v);
}

interface Names {
  track: (t: number) => string;
  curve: (c: number) => string;
}

function print(e: PExpr, names: Names, used: Set<string>): string {
  const p = (x: PExpr) => print(x, names, used);
  switch (e.k) {
    case "lit":
      return num(e.v);
    case "slot":
      return `s${e.i}`;
    case "tick":
      return "tick";
    case "bin":
      return `(${p(e.a)} ${e.op} ${p(e.b)})`;
    case "cmp": {
      const op = e.op === "==" ? "===" : e.op === "!=" ? "!==" : e.op;
      return `(${p(e.a)} ${op} ${p(e.b)} ? 1 : 0)`;
    }
    case "neg":
      return `(-${p(e.a)})`;
    case "not":
      return `(${p(e.a)} ? 0 : 1)`;
    case "and":
      return `(${p(e.a)} && ${p(e.b)})`;
    case "or":
      return `(${p(e.a)} || ${p(e.b)})`;
    case "cond":
      return `(${p(e.c)} ? ${p(e.a)} : ${p(e.b)})`;
    case "track":
      return `(evaluateTrack(${names.track(e.t)}, ${p(e.at)}) as number)`;
    case "rand":
      used.add("rand");
      return `tbxRand((r${e.r} = (r${e.r} + 0x6d2b79f5) | 0))`;
    case "call": {
      const args = e.args.map(p);
      const f = e.fn;
      if (f in MATH_FNS || MATH_VARIADIC.has(f)) return `Math.${f}(${args.join(", ")})`;
      if (f in ENV_HELPERS) {
        used.add(f);
        return `${helperName(f)}(${args.join(", ")})`;
      }
      if (f.startsWith("ease:")) {
        used.add(f);
        return `${easeFnName(f.slice(5))}(${args.join(", ")})`;
      }
      if (f.startsWith("curve:")) {
        used.add("curve");
        return `tbxCurve(${names.curve(Number(f.slice(6)))}, ${args.join(", ")})`;
      }
      switch (f) {
        case "toNum":
          used.add("toNum");
          return `tbxNum(${args[0]})`;
        case "isFinite":
          return `(Number.isFinite(${args[0]}) ? 1 : 0)`;
        case "fixed6":
          return `parseFloat((${args[0]}).toFixed(6))`;
        case "seed32":
          used.add("seed32");
          return `tbxSeed32(${args.join(", ")})`;
        case "hash01":
          used.add("hash01");
          return `tbxHash01(${args.join(", ")})`;
        case "frameOf":
          return `Math.floor(${args[0]} / ${args[1]})`;
        case "lfoPhase":
          used.add("lfoPhase");
          return `tbxLfoPhase(${args.join(", ")})`;
      }
      throw new Error(`procedural emit-js: no JS form for ${f}`);
    }
  }
}

export interface ProceduralValue {
  // Bundle key (uniform name / bind id) — the function is P_<key>.
  key: string;
  program: ProcProgram;
  // One-line provenance for the comment.
  from: string;
}

export function proceduralFnName(key: string): string {
  return `P_${key.replace(/[^A-Za-z0-9_$]/g, "_")}`;
}

// The procedural.ts module for a bundle's procedural values.
export function emitProceduralModule(values: ProceduralValue[]): string {
  const used = new Set<string>();
  const data: string[] = [];
  const fns: string[] = [];
  let anyTrack = false;
  values.forEach((v, vi) => {
    const prog = v.program;
    const names: Names = {
      track: (t) => `PT_${vi}_${t}`,
      curve: (c) => `PC_${vi}_${c}`,
    };
    const lines: string[] = [];
    const refTracks = new Set<number>();
    const refCurves = new Set<number>();
    const scan = (e: PExpr) => {
      if (e.k === "track") refTracks.add(e.t);
      if (e.k === "call" && e.fn.startsWith("curve:")) refCurves.add(Number(e.fn.slice(6)));
      for (const k of ["a", "b", "c", "at"] as const) {
        const x = (e as Record<string, unknown>)[k];
        if (x && typeof x === "object") scan(x as PExpr);
      }
      if (e.k === "call") e.args.forEach(scan);
    };
    prog.body.forEach((s) => scan(s.k === "let" ? s.e : s.seed));
    scan(prog.out);
    for (const t of [...refTracks].sort((a, b) => a - b)) {
      anyTrack = true;
      data.push(`const ${names.track(t)}: TimelineTrack = ${JSON.stringify(prog.tracks[t])};`);
    }
    for (const c of [...refCurves].sort((a, b) => a - b)) data.push(`const ${names.curve(c)} = ${JSON.stringify(prog.curves[c])};`);
    prog.body.forEach((s, i) => {
      if (s.k === "rng") lines.push(`let r${s.r} = ${print(s.seed, names, used)};`);
      else lines.push(`const s${i} = ${print(s.e, names, used)};${s.note ? ` // ${s.note.replace(/\n/g, " ")}` : ""}`);
    });
    const ret = print(prog.out, names, used);
    fns.push(
      `// ${v.key}: ${v.from}\nexport function ${proceduralFnName(v.key)}(tick: number): number {\n  "worklet";\n${lines.map((l) => `  ${l}\n`).join("")}  return ${ret};\n}`
    );
  });
  const helpers = helperSources(used);
  return (
    HEADER +
    (anyTrack ? `\nimport { evaluateTrack, type TimelineTrack } from "./toolbox-timeline";\n` : "") +
    (helpers.length ? `\n${helpers.join("\n\n")}\n` : "") +
    (data.length ? `\n${data.join("\n")}\n` : "") +
    `\n${fns.join("\n\n")}\n`
  );
}
