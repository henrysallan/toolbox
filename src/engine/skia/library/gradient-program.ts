// Gradient shaders as color-managed runtime programs
// (specdocs/101326_skia-target.md §5.5, Wave 3 lane C).
//
// The scene IR's gradient kinds (linear / radial / sweep / conical) promise
// sRGB interpolation (scene-ir.ts: "Skia gradients interpolate in sRGB").
// Skia keeps that promise only on an sRGB canvas: it interpolates a native
// gradient in the DESTINATION's working space, so on React Native Skia's
// Display P3 iPhone canvas the in-between colors shift (a red → blue linear
// gradient: 24/255, measured by check:skia-color-management) — and React
// Native Skia exposes no interpolation color space. One export runs on iOS
// and Android alike, so both consumers lower EVERY gradient to the program
// below, always (no per-platform branch):
//
//   preview  scene-render.ts   draws gradientProgram() instead of
//                              MakeLinearGradient & co.
//   export   scene-plan.ts     lowerSceneGradients() before planning, so the
//                              emitters only ever see runtime programs
//                              (<Shader> + uniforms in the JSX)
//
// The program reproduces Skia's gradient semantics on sRGB numbers — the
// stop list piecewise linear in unpremultiplied color, positions clamped
// monotonic with implicit end stops, the four tile modes, Skia's degenerate
// rules (SkGradientBaseShader::kDegenerateThreshold, MakeDegenerateGradient)
// — and hands the result to tbx_cm_out (sRGB → the working space,
// premultiplied). On an sRGB canvas that is the native gradient (≤ 1/255:
// float vs Skia's own interpolation pipeline); on Display P3 it is the same
// sRGB color, converted.
//
// Binds are reused, never re-derived: each stop color is its own float4
// uniform holding the IR's Bind object (a keyframed stop color stays a
// track), geometry values are float uniforms on their own Binds; stop
// positions pack four to a float4 (one composite Bind; static when all four
// are, else derived with their refs / deps as deps). The SkSL depends only
// on the kind, the stop count and the tile mode, so an animated gradient
// keeps one program.
//
// Cost: per pixel, the geometry (a dot, a length, an atan or a quadratic),
// n position clamps, a binary if-tree to the stop interval (⌈log2 n⌉
// compares) and one mix, then the color management (two transfer
// functions and Skia's transform; skipped on sRGB by the probe's select).
// Uniforms: one float4 per stop, one float4 per four positions, up to six
// floats of geometry — n stops take n + ⌈n/4⌉ + 2 vec4 slots on a GL
// backend (a 49-stop OKLab ramp from Gradient Fill (Skia): 64). Measured
// (spec §4): about 2× a native gradient's GPU time for 2–6 stops.
// check:skia-color-management prints CPU raster times (relative only).

import { bindStatic, type Bind, type BindRef, type ImageFilterIR, type PaintIR, type ShaderIR, type SkiaNode, type SkiaScene, type SkslProgramIR, type TileMode } from "../scene-ir";
import { colorManagementSksl } from "./color-management";

export type GradientShaderIR = Extract<ShaderIR, { k: "linear" | "radial" | "sweep" | "conical" }>;

export const GRADIENT_PROGRAM_MARKER = "// Generated by toolbox (engine/skia/library/gradient-program.ts)";

export function isGradientShader(s: ShaderIR | null | undefined): s is GradientShaderIR {
  return !!s && (s.k === "linear" || s.k === "radial" || s.k === "sweep" || s.k === "conical");
}

// SkGradientBaseShader::kDegenerateThreshold (1 / 2^15).
const DEGENERATE = "0.000030517578125";
const TILES: readonly TileMode[] = ["clamp", "repeat", "mirror", "decal"];

// Four positions → one float4 uniform's Bind.
function packPositions(binds: Bind<number>[]): Bind<number[]> {
  const v = [0, 1, 2, 3].map((k) => (binds[k] ? binds[k].v : 1));
  const deps: BindRef[] = [];
  let derived = false;
  for (const b of binds) {
    if (b.ref) {
      deps.push(b.ref);
      derived = true;
    }
    if (b.deps) {
      deps.push(...b.deps);
      derived = true;
    }
  }
  return derived ? { v, deps } : { v };
}

// The stop list's SkSL: ramp(t) for t in 0..1 (after tiling), and the
// average color Skia shows for a degenerate repeat / mirror gradient.
function rampSksl(n: number, withAverage: boolean): string {
  const P = (i: number) => `tbx_g_p${i >> 2}.${"xyzw"[i & 3]}`;
  const C = (i: number) => `tbx_g_c${i}`;
  const lines: string[] = [];
  lines.push(`float tbx_g_seg(float t, float a, float b) {`, `  return b > a ? clamp((t - a) / (b - a), 0.0, 1.0) : 1.0;`, `}`);
  // Skia fixes positions on construction: the first into 0..1, each next
  // into [previous, 1]; t below the first stop is the first color, above
  // the last the last color.
  lines.push(`float4 tbx_g_ramp(float t) {`);
  lines.push(`  float q0 = clamp(${P(0)}, 0.0, 1.0);`);
  for (let i = 1; i < n; i++) lines.push(`  float q${i} = clamp(${P(i)}, q${i - 1}, 1.0);`);
  // The interval t falls in — the LAST i with q(i-1) ≤ t, so a hard stop
  // (two equal positions) shows the later color from its position on, as
  // Skia does — by a binary if-tree: ⌈log2 n⌉ compares and one mix per pixel
  // (a GPU takes one branch; neighbouring pixels share it).
  const tree = (lo: number, hi: number, pad: string): string[] => {
    if (lo === hi) return [`${pad}return mix(${C(lo - 1)}, ${C(lo)}, tbx_g_seg(t, q${lo - 1}, q${lo}));`];
    const mid = Math.ceil((lo + hi) / 2);
    return [`${pad}if (t >= q${mid - 1}) {`, ...tree(mid, hi, `${pad}  `), `${pad}} else {`, ...tree(lo, mid - 1, `${pad}  `), `${pad}}`];
  };
  lines.push(`  if (t < q0) return ${C(0)};`, ...tree(1, n - 1, "  "), `}`);
  if (withAverage) {
    // SkGradientBaseShader's average_gradient_color: each interval's mean
    // weighted by its length (positions pinned per interval, as Skia pins
    // them there), plus the implicit spans before the first stop and after
    // the last.
    lines.push(`float4 tbx_g_average() {`, `  float4 s = float4(0.0);`);
    for (let i = 0; i + 1 < n; i++) {
      lines.push(`  {`, `    float a = clamp(${P(i)}, 0.0, 1.0);`, `    float b = clamp(${P(i + 1)}, a, 1.0);`);
      if (i === 0) lines.push(`    s += a * ${C(0)};`);
      if (i === n - 2) lines.push(`    s += (1.0 - b) * ${C(n - 1)};`);
      lines.push(`    s += 0.5 * (b - a) * (${C(i)} + ${C(i + 1)});`, `  }`);
    }
    lines.push(`  return s;`, `}`);
  }
  return lines.join("\n");
}

// t → the tiled t, and whether the pixel is drawn (decal).
function tileSksl(tile: TileMode): string {
  switch (tile) {
    case "repeat":
      return `  t = t - floor(t);`;
    case "mirror":
      return `  t = abs((t - 1.0) - 2.0 * floor((t - 1.0) * 0.5) - 1.0);`;
    case "decal":
      return `  visible = visible && t >= 0.0 && t <= 1.0;\n  t = clamp(t, 0.0, 1.0);`;
    default:
      return `  t = clamp(t, 0.0, 1.0);`;
  }
}

// What Skia draws for a degenerate gradient (MakeDegenerateGradient):
// clamp → the last color, repeat / mirror → the average color, decal →
// nothing.
function degenerateSksl(n: number, tile: TileMode): { color: string; hides: boolean } {
  if (tile === "decal") return { color: `tbx_g_c${n - 1}`, hides: true };
  if (tile === "repeat" || tile === "mirror") return { color: "tbx_g_average()", hides: false };
  return { color: `tbx_g_c${n - 1}`, hides: false };
}

// The preview rebuilds the program every frame: the helper block and the
// ramp (the long parts) are cached.
let cmText: string | null = null;
const cmSksl = () => (cmText ??= colorManagementSksl());
const rampText = new Map<string, string>();
function rampFor(n: number, withAverage: boolean): string {
  const key = `${n}:${withAverage}`;
  let t = rampText.get(key);
  if (t === undefined) {
    t = rampSksl(n, withAverage);
    rampText.set(key, t);
  }
  return t;
}

// The runtime program a gradient lowers to. `g` must have ≥ 1 stop (the
// renderer reports an empty stop list before calling this).
export function gradientProgram(g: GradientShaderIR): SkslProgramIR {
  const n = g.stops.length;
  const tile: TileMode = g.k === "sweep" ? "clamp" : TILES.includes(g.tile as TileMode) ? (g.tile as TileMode) : "clamp";
  const uniforms: Record<string, Bind<number | number[]>> = {};
  const decl: string[] = [];
  const scalar = (name: string, b: Bind<number>) => {
    uniforms[name] = b;
    decl.push(`uniform float ${name};`);
  };
  switch (g.k) {
    case "linear":
      scalar("tbx_g_x0", g.start[0]);
      scalar("tbx_g_y0", g.start[1]);
      scalar("tbx_g_x1", g.end[0]);
      scalar("tbx_g_y1", g.end[1]);
      break;
    case "radial":
      scalar("tbx_g_cx", g.c[0]);
      scalar("tbx_g_cy", g.c[1]);
      scalar("tbx_g_r", g.r);
      break;
    case "sweep":
      scalar("tbx_g_cx", g.c[0]);
      scalar("tbx_g_cy", g.c[1]);
      // IR angles are radians (RN: degrees; the program converts as the
      // renderer did).
      scalar("tbx_g_a0", g.start ?? bindStatic(0));
      scalar("tbx_g_a1", g.end ?? bindStatic(2 * Math.PI));
      break;
    case "conical":
      scalar("tbx_g_x0", g.c0[0]);
      scalar("tbx_g_y0", g.c0[1]);
      scalar("tbx_g_r0", g.r0);
      scalar("tbx_g_x1", g.c1[0]);
      scalar("tbx_g_y1", g.c1[1]);
      scalar("tbx_g_r1", g.r1);
      break;
  }
  g.stops.forEach((s, i) => {
    uniforms[`tbx_g_c${i}`] = s.color;
    decl.push(`uniform float4 tbx_g_c${i};  // stop ${i}: straight alpha, sRGB`);
  });
  for (let k = 0; 4 * k < n; k++) {
    uniforms[`tbx_g_p${k}`] = packPositions(g.stops.slice(4 * k, 4 * k + 4).map((s) => s.pos));
    decl.push(`uniform float4 tbx_g_p${k};  // stop positions ${4 * k}..${Math.min(n, 4 * k + 4) - 1}`);
  }

  const deg = degenerateSksl(n, tile);
  const last = `tbx_g_c${n - 1}`;
  const body: string[] = [];
  if (n === 1) {
    // One color: Skia draws it everywhere, whatever the geometry or tile.
    body.push(`  return tbx_cm_out(tbx_g_c0);`);
  } else {
    body.push(`  bool visible = true;`, `  float t = 0.0;`, `  bool degenerate = false;`);
    // A hard stop at 1 after the first color: Skia's stand-in for a sweep /
    // a concentric conical gradient collapsed to a line or a ring (clamp).
    let ring = "";
    switch (g.k) {
      case "linear":
        body.push(
          `  float2 a = float2(tbx_g_x0, tbx_g_y0);`,
          `  float2 d = float2(tbx_g_x1, tbx_g_y1) - a;`,
          `  float dd = dot(d, d);`,
          `  degenerate = sqrt(dd) <= ${DEGENERATE};`,
          `  t = degenerate ? 0.0 : dot(p - a, d) / dd;`
        );
        break;
      case "radial":
        body.push(`  degenerate = tbx_g_r <= ${DEGENERATE};`, `  t = degenerate ? 0.0 : length(p - float2(tbx_g_cx, tbx_g_cy)) / tbx_g_r;`);
        break;
      case "sweep":
        // Skia's sweep: the angle from +x, clockwise on a Y-down canvas, as
        // a 0..1 turn; start / end (degrees) rescale it; clamp.
        body.push(
          `  float2 d = p - float2(tbx_g_cx, tbx_g_cy);`,
          `  float u = atan(-d.y, -d.x) * 0.15915494309189535 + 0.5;`,
          `  float a0 = tbx_g_a0 * 57.29577951308232;`,
          `  float a1 = tbx_g_a1 * 57.29577951308232;`,
          `  degenerate = abs(a1 - a0) <= ${DEGENERATE};`,
          `  // Collapsed with an end angle > 0 (clamp): the first color up to the end, then the last.`,
          `  bool ring = degenerate && a1 > ${DEGENERATE};`,
          `  t = ring ? u * 360.0 / a1 : degenerate ? 0.0 : (u - a0 / 360.0) * (360.0 / (a1 - a0));`
        );
        ring = "ring";
        break;
      case "conical":
        // Two-point conical (the Canvas / PDF rule): the largest t whose
        // circle c(t) = c0 + t·(c1 − c0), r(t) = r0 + t·(r1 − r0) ≥ 0 passes
        // through p; no such t draws nothing. Concentric and collapsed
        // circles take Skia's special cases.
        body.push(
          `  float2 c0 = float2(tbx_g_x0, tbx_g_y0);`,
          `  float2 cd = float2(tbx_g_x1, tbx_g_y1) - c0;`,
          `  float dr = tbx_g_r1 - tbx_g_r0;`,
          `  float2 pd = p - c0;`,
          `  bool concentric = length(cd) <= ${DEGENERATE};`,
          `  degenerate = concentric && abs(dr) <= ${DEGENERATE};`,
          tile === "clamp"
            ? `  // Collapsed to one circle of radius r1 > 0 (clamp): the first color inside, the last outside.\n  bool ring = degenerate && tbx_g_r1 > ${DEGENERATE};`
            : `  bool ring = false;  // (the collapsed-ring stand-in is clamp-only)`,
          `  if (ring) {`,
          `    t = length(pd) / tbx_g_r1;`,
          `  } else if (degenerate) {`,
          `    t = 0.0;`,
          `  } else if (concentric && tbx_g_r0 <= ${DEGENERATE}) {`,
          `    t = length(pd) / tbx_g_r1;`,
          `  } else {`,
          `    float qa = dot(cd, cd) - dr * dr;`,
          `    float qb = dot(pd, cd) + tbx_g_r0 * dr;`,
          `    float qc = dot(pd, pd) - tbx_g_r0 * tbx_g_r0;`,
          `    if (abs(qa) <= 0.000001 * max(dot(cd, cd) + dr * dr, 0.000000000001)) {`,
          `      t = qc / (2.0 * qb);`,
          `      visible = abs(qb) > 0.0 && tbx_g_r0 + t * dr >= 0.0;`,
          `    } else {`,
          `      float disc = qb * qb - qa * qc;`,
          `      float sq = sqrt(max(disc, 0.0));`,
          `      float hi = max((qb + sq) / qa, (qb - sq) / qa);`,
          `      float lo = min((qb + sq) / qa, (qb - sq) / qa);`,
          `      bool hiOk = tbx_g_r0 + hi * dr >= 0.0;`,
          `      t = hiOk ? hi : lo;`,
          `      visible = disc >= 0.0 && (hiOk || tbx_g_r0 + lo * dr >= 0.0);`,
          `    }`,
          `  }`
        );
        if (tile === "clamp") ring = "ring";
        break;
    }
    // The ring stand-in reads t before tiling.
    if (ring) body.push(`  float4 ringColor = t < 1.0 ? tbx_g_c0 : ${last};`);
    body.push(tileSksl(tile));
    body.push(`  float4 c = ${ring ? `${ring} ? ringColor : ` : ""}degenerate ? ${deg.color} : tbx_g_ramp(t);`);
    // (decal never has the ring stand-in: that is clamp-only.)
    if (deg.hides) body.push(`  visible = visible && !degenerate;`);
    body.push(`  half4 o = tbx_cm_out(c);`, `  return visible ? o : half4(0.0);`);
  }

  const sksl = [
    `${GRADIENT_PROGRAM_MARKER}: a ${g.k} gradient, ${n} stop${n === 1 ? "" : "s"}, tile ${tile}.`,
    "// Interpolates in sRGB, then converts to the canvas's color space (tbx_cm_out),",
    "// so it draws the same colors on sRGB and Display P3 canvases.",
    ...decl,
    cmSksl(),
    ...(n > 1 ? [rampFor(n, deg.color === "tbx_g_average()")] : []),
    "half4 main(float2 p) {",
    ...body,
    "}",
    "",
  ].join("\n");
  return { sksl, uniforms, children: [], fused: [`tbx.gradient.${g.k}`] };
}

// ---- lowering a scene ---------------------------------------------------------------

// Every gradient in a shader tree as its program (runtime children too).
export function lowerShaderGradients(s: ShaderIR): ShaderIR {
  if (isGradientShader(s)) return { k: "runtime", program: gradientProgram(s) };
  if (s.k === "runtime") {
    const kids = s.program.children;
    const lowered = kids.map((c) => (c && c.shader ? { ...c, shader: lowerShaderGradients(c.shader) } : c));
    return lowered.some((c, i) => c !== kids[i]) ? { k: "runtime", program: { ...s.program, children: lowered } } : s;
  }
  return s;
}

function lowerPaint(p: PaintIR): PaintIR {
  if (!p?.shader) return p;
  const shader = lowerShaderGradients(p.shader);
  return shader === p.shader ? p : { ...p, shader };
}

function lowerImageFilter(f: ImageFilterIR): ImageFilterIR {
  if (f?.k === "displacement" && f.map) {
    const map = lowerShaderGradients(f.map);
    return map === f.map ? f : { ...f, map };
  }
  if (f?.k === "runtime" && f.program) {
    const s = lowerShaderGradients({ k: "runtime", program: f.program });
    return s.k === "runtime" && s.program !== f.program ? { ...f, program: s.program } : f;
  }
  return f;
}

function lowerNode(n: SkiaNode): SkiaNode {
  if (!n || typeof n !== "object") return n;
  switch (n.k) {
    case "group": {
      const children = Array.isArray(n.children) ? n.children.map(lowerNode) : n.children;
      const filters = n.layer?.imageFilters;
      const lowered = Array.isArray(filters) ? filters.map(lowerImageFilter) : filters;
      const layerChanged = Array.isArray(filters) && lowered!.some((x, i) => x !== filters[i]);
      const kidsChanged = Array.isArray(n.children) && (children as SkiaNode[]).some((c, i) => c !== n.children[i]);
      if (!layerChanged && !kidsChanged) return n;
      return { ...n, children: children as SkiaNode[], ...(layerChanged ? { layer: { ...n.layer, imageFilters: lowered } } : {}) };
    }
    case "fill":
    case "shape":
    case "text": {
      const paint = lowerPaint(n.paint);
      return paint === n.paint ? n : { ...n, paint };
    }
    case "atlas": {
      // A sprite sheet drawn from a sub-scene (useTexture): its gradients
      // lower too, as the preview's drawNode lowers them in the sheet.
      const t = n.texture;
      if (!t || !t.node) return n;
      const sub = lowerNode(t.node);
      return sub === t.node ? n : { ...n, texture: { ...t, node: sub } };
    }
    default:
      return n;
  }
}

// The scene with every gradient lowered to its program (shared structure;
// Bind objects are the scene's own). The exporter plans this, so the bundle
// draws exactly what the preview draws.
export function lowerSceneGradients(scene: SkiaScene): SkiaScene {
  if (!scene || !scene.root) return scene;
  const root = lowerNode(scene.root);
  return root === scene.root ? scene : { ...scene, root };
}
