// Expo config plugin: let the harness POST captures to the parity collector
// over plain http on loopback only (capture.ts; scripts/skia-device-parity.mjs).
//
// Android 9+ refuses cleartext http in release builds, and the device lanes
// build Release (the JS bundle is embedded, so no Metro server is needed).
// This adds res/xml/toolbox_loopback_http.xml permitting cleartext to
// 10.0.2.2 (the emulator's host loopback), 127.0.0.1 and localhost, and
// nothing else, and points the manifest's networkSecurityConfig at it.
// iOS needs no plugin: app.json sets NSAllowsLocalNetworking.
const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const XML_NAME = "toolbox_loopback_http";
const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-loopback-http.js: cleartext http to loopback only. -->
<network-security-config>
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">10.0.2.2</domain>
    <domain includeSubdomains="false">127.0.0.1</domain>
    <domain includeSubdomains="false">localhost</domain>
  </domain-config>
</network-security-config>
`;

module.exports = function withLoopbackHttp(config) {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${XML_NAME}.xml`), XML);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$["android:networkSecurityConfig"] = `@xml/${XML_NAME}`;
    return cfg;
  });
};
