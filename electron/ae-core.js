// A JavaScript string literal that is pure ASCII (ExtendScript's source
// decoding is not trusted with UTF-8) and safe for any input.
function jsString(s) {
  return `"${String(s).replace(/[^\x20-\x7e]|["\\]/g, (ch) => {
    if (ch === '"') return '\\"';
    if (ch === "\\") return "\\\\";
    return `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`;
  })}"`;
}

// The driver main writes into its own temp folder for one build: build.jsx
// globals, then main's verified copy of build.jsx, then a done marker.
function driverSource({ buildJsx, packageDir, doneFile }) {
  return [
    "// Generated by Toolbox (electron/ae.js) for one headless After Effects build.",
    "$.global.TBX_AE_QUIET = true;",
    "$.global.TBX_AE_OVERWRITE = true;",
    `$.global.TBX_AE_PACKAGE = ${jsString(packageDir)};`,
    "$.global.TBX_AE_RESULT = null;",
    "app.setSavePreferencesOnQuit(false);",
    "(function () {",
    "  var err = null;",
    "  try {",
    `    $.evalFile(new File(${jsString(buildJsx)}));`,
    "  } catch (e) {",
    '    err = String(e) + (e && e.line ? " (line " + e.line + ")" : "");',
    "  }",
    "  var r = $.global.TBX_AE_RESULT;",
    `  var f = new File(${jsString(doneFile)});`,
    '  f.encoding = "UTF-8";',
    '  f.lineFeed = "Unix";',
    '  if (f.open("w")) {',
    '    f.write((r && r.ok ? "ok" : "failed") + "\\n" + (r && r.saved ? r.saved : "") + "\\n" + (err || "") + "\\n");',
    "    f.close();",
    "  }",
    "}());",
    "",
  ].join("\n");
}

// Where After Effects may be: TOOLBOX_AE_DIR first (a folder holding
// aerender), then the release folders newest first, then the beta.
const AE_YEARS = [2027, 2026, 2025, 2024];
function aeCandidateDirs(env = process.env, platform = process.platform) {
  if (platform !== "darwin") return [];
  const out = [];
  if (env.TOOLBOX_AE_DIR) out.push({ dir: env.TOOLBOX_AE_DIR, source: "env" });
  for (const y of AE_YEARS) out.push({ dir: `/Applications/Adobe After Effects ${y}`, source: "default" });
  out.push({ dir: "/Applications/Adobe After Effects (Beta)", source: "default" });
  return out.map((c) => ({
    ...c,
    aerender: path.join(c.dir, "aerender"),
    app: path.join(c.dir, `${path.basename(c.dir)}.app`),
  }));
}

// "26.5.0" → "26.5": the Preferences folder AE reads Scripts/Startup from.
function prefsVersionOf(appVersion) {
  const m = /^(\d+)\.(\d+)/.exec(String(appVersion || ""));
  return m ? `${Number(m[1])}.${Number(m[2])}` : null;
}

// Pick the Preferences folder: the app's major.minor when it exists, else the
// highest existing folder with the same major.
function pickPrefsVersion(appVersion, existing) {
  const want = prefsVersionOf(appVersion);
  if (!want) return null;
  if (existing.includes(want)) return want;
  const major = want.split(".")[0];
  const same = existing
    .filter((v) => /^\d+\.\d+$/.test(v) && v.split(".")[0] === major)
    .sort((a, b) => Number(b.split(".")[1]) - Number(a.split(".")[1]));
  return same[0] ?? want;
}

// tbxshader-check: TOOLBOX_SHADER_CHECK (or the translator lane's
// TBX_SHADER_CHECK), else ../AE_Plugins/toolbox-shader/build next to any
// ancestor of the app folder (a git worktree sits a few levels below the
// checkout). `exists` is injected for the gate.
function shaderCheckCandidates(env, startDir) {
  const out = [];
  if (env.TOOLBOX_SHADER_CHECK) out.push({ path: env.TOOLBOX_SHADER_CHECK, source: "env" });
  if (env.TBX_SHADER_CHECK) out.push({ path: env.TBX_SHADER_CHECK, source: "env" });
  let dir = path.resolve(startDir);
  for (let i = 0; i < 8; i++) {
    const parent = path.dirname(dir);
    if (parent === dir) break;
    out.push({ path: path.join(parent, "AE_Plugins", "toolbox-shader", "build", "tbxshader-check"), source: "dev" });
    dir = parent;
  }
  return out;
}

