const MAX_RENDER_FRAMES = 8;

// One aerender render launch: frame `frame` of `comp` (inclusive -s/-e)
// through the shipped "TIFF Sequence with Alpha" output module (8-bit,
// premultiplied, spec §13). Every path and the comp name must pass
// aerenderSafe; throws otherwise.
function renderArgs({ project, comp, output, frame }) {
  for (const [what, v] of [["project", project], ["output", output]]) {
    const ok = aerenderSafe(v);
    if (!ok.ok) throw new Error(`aerender ${what}: ${ok.reason}`);
  }
  // eslint-disable-next-line no-control-regex
  if (typeof comp !== "string" || !comp || /["\\\u0000-\u001f\u007f-\u009f\u2028\u2029]/.test(comp))
    throw new Error(`aerender -comp: the comp name ${JSON.stringify(comp)} has a double quote, backslash or control character — rename the composition`);
  if (!Number.isInteger(frame) || frame < 0 || frame > 1_000_000) throw new Error(`aerender frame must be a whole number ≥ 0 (got ${frame})`);
  return [
    "-project", project,
    "-comp", comp,
    "-RStemplate", "Best Settings",
    "-OMtemplate", "TIFF Sequence with Alpha",
    "-output", output,
    "-s", String(frame),
    "-e", String(frame),
    "-sound", "OFF",
  ];
}

// aerender's TIFF frames are premultiplied (matted on black): straight RGBA8
// in place, the way toolbox's readback is.
function unpremultiply(rgba) {
  for (let i = 0; i < rgba.length; i += 4) {
    const a = rgba[i + 3];
    if (a === 0 || a === 255) continue;
    for (let c = 0; c < 3; c++) rgba[i + c] = Math.min(255, Math.round((rgba[i + c] * 255) / a));
  }
  return rgba;
}

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

// scene.json → the main comp aerender renders (name, size, fps), or why not.
function mainCompOf(sceneText) {
  let scene;
  try {
    scene = JSON.parse(sceneText);
  } catch (e) {
    throw new Error(`scene.json is not JSON: ${e && e.message ? e.message : e}`);
  }
  const comps = scene && Array.isArray(scene.comps) ? scene.comps : [];
  const c = comps.find((x) => x && x.id === scene.main);
  if (!c || typeof c.name !== "string") throw new Error("scene.json names no main comp");
  const w = Math.round(Number(c.width));
  const h = Math.round(Number(c.height));
  const fps = Number(c.fps);
  if (!(w > 0 && h > 0 && w <= 30000 && h <= 30000 && fps > 0)) throw new Error("scene.json's main comp has no valid size / fps");
  return { id: c.id, name: c.name, width: w, height: h, fps, duration: Number(c.duration) || 0 };
}

