// The pure half of electron/ae.js (After Effects on the desktop, spec
// 091926_after-effects-handoff.md §5.3, §7.5, §8, §13): where After Effects
// lives, the one-launch startup hook, the build driver, aerender's render
// arguments and the TIFF unpremultiply. No Electron imports and no process
// spawning, so scripts/ae-export/check-package-paths.mts tests it offline.
//
// How a headless build runs (measured in AE 26.5, spec §13): aerender
// launches its render core (aerendercore, a separate app from the After
// Effects GUI, which is never contacted), and the core evaluates the USER
// Scripts/Startup folder before it reads its command line. So for one
// aerender launch main copies HOOK_SOURCE there; the hook evaluates the
// driver named by HOOK_ENV, which only main sets, in aerender's environment.
// The build launch passes aerender only BUILD_ARGS — no project, so it
// launches the core, renders nothing and quits with exit 0 (measured
// 2026-10-20; with no arguments at all it prints its usage and never starts
// the core) — so no path reaches aerender's unescaped argument pasting. Renders pass -project / -comp / -output,
// all built by main and checked by safe-paths.aerenderSafe.
"use strict";

